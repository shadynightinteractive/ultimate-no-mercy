"""src/ann_slot.h: a model slot's arrays (the main segment's per-model arrays, six/spec.py MAIN), stock and
six-man places, for announce.c (a slot borrowed to build the announcers' models, then put back)."""
import os as _os, sys as _sys; _sys.path.append(next(d for d in (_os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), *[".."] * i)) for i in range(8)) if _os.path.exists(_os.path.join(d, "nmpaths.py"))))
from nmpaths import nmp
import sys
sys.argv = ['x']; sys.path.insert(0, nmp('/home/devbox/work/six'))
import build_rom
L = ['// Generated by gen/mkannsave.py: a model slot\'s arrays {place, size per slot} (six/spec.py MAIN).', '#pragma once',
     'typedef struct { unsigned int at, size, stock; } AnnSlotArray;', '#ifdef NM_SIX', 'static const AnnSlotArray ann_slot_arrays[] = {']
PER_MODEL = [x for x in build_rom.MAIN_NEW if x[0] not in getattr(build_rom.spec, 'MAIN_SHARED', ())]   # (not the frame's shared lists)
for b, s, n, w in PER_MODEL: L.append('    { 0x%08Xu, 0x%X, 0x%08Xu },   // %s' % (n, s, b, w))
L += ['};', '#else', 'static const AnnSlotArray ann_slot_arrays[] = {']
for b, s, n, w in PER_MODEL: L.append('    { 0x%08Xu, 0x%X, 0x%08Xu },   // %s' % (b, s, b, w))
L += ['};', '#endif', '#define ANN_SLOT_ARRAYS (sizeof(ann_slot_arrays) / sizeof(ann_slot_arrays[0]))', '']
open(nmp('/home/devbox/work/arcade/src/ann_slot.h'), 'w').write('\n'.join(L))
print(sum(s for b, s, n, w in PER_MODEL), "bytes per slot")
