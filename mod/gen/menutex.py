"""Renders the replacement main-menu labels as CI4 (grey-ramp palette: index = intensity, 0 = clear,
1 = outline) in the style of the game's own labels. Writes src/menu_tex.h."""
import numpy as np
from PIL import Image, ImageDraw, ImageFont
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf"
def label(text, w, h=32, cap=16, x0=5, y0=1):
    S = 4
    f = ImageFont.truetype(FONT, 10)
    # size the font so a capital is `cap` px tall
    size = 10
    while True:
        f = ImageFont.truetype(FONT, size * S)
        bb = f.getbbox("H")
        if bb[3] - bb[1] >= cap * S: break
        size += 0.5
    img = Image.new("L", (w * S, h * S), 0)
    dr = ImageDraw.Draw(img)
    bb = f.getbbox("H")
    # squeeze horizontally to fit
    tw = f.getlength(text)
    sx = min(1.0, (w - x0 - 3) * S / tw)
    tmp = Image.new("L", (int(tw) + 8 * S, h * S), 0)
    ImageDraw.Draw(tmp).text((0, y0 * S - bb[1] + 2 * S), text, font=f, fill=255, stroke_width=int(0.4 * S), stroke_fill=255)
    tmp = tmp.resize((max(1, int(tmp.width * sx * 0.92)), tmp.height), Image.LANCZOS)
    img.paste(tmp, (x0 * S, 0))
    a = np.asarray(img.resize((w, h), Image.LANCZOS), dtype=np.float32) / 255.0
    idx = np.clip(np.round(a * 15), 0, 15).astype(np.uint8)
    idx[idx < 3] = 0
    # 1-px outline (index 1) around the glyphs
    m = idx > 0
    o = np.zeros_like(m)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            o |= np.roll(np.roll(m, dy, 0), dx, 1)
    idx[(o) & (~m)] = 1
    return idx
def ci4(idx):
    f = idx.reshape(-1)
    return bytes(((f[0::2] << 4) | f[1::2]).tolist())
def carr(name, b):
    s = "static const unsigned char %s[%d] __attribute__((aligned(8))) = {\n" % (name, len(b))
    for i in range(0, len(b), 16): s += "  " + ",".join("0x%02x" % v for v in b[i:i + 16]) + ",\n"
    return s + "};\n"
if __name__ == "__main__":
    import sys
    v = label("Versus", 96); s = label("Story Mode", 128)
    out = "// generated by gen/menutex.py: main-menu labels, CI4 on the game's grey-ramp palette\n"
    out += carr("tex_versus", ci4(v)) + carr("tex_story", ci4(s))
    open(sys.argv[1] if len(sys.argv) > 1 else "../src/menu_tex.h", "w").write(out)
    for n, a in (("v", v), ("s", s)):
        for r in a: print("".join(" .:-=+*#%@ABCDEF"[x] for x in r))
