#!/usr/bin/env python3
"""The photos (Superstar Select) of the No Mercy Plus V3 Superstars added after the Meanie (gen/mkparts.py
OVR2: photos 105 on) -> src/photos_nm.h. No Mercy Plus keeps photo p's TEX file (64 x 64 CI4) at 0x4C21 + p."""
import os as _os, sys as _sys; _sys.path.append(next(d for d in (_os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), *[".."] * i)) for i in range(8)) if _os.path.exists(_os.path.join(d, "nmpaths.py"))))
from nmpaths import nmp
import sys
sys.path.insert(0, nmp("/home/devbox/work/arcade/gen"))
import mkparts as P
L = ["// generated by gen/mkphotos.py: No Mercy Plus V3's photos for the Superstars after the Meanie",
     "typedef struct { u8 photo; u8 tlut[32]; u8 ci4[2048]; } NmPhoto;",
     "#define NM_PHOTOS_N %d" % len(P.OVR2), "static const NmPhoto nm_photos[NM_PHOTOS_N] = {"]
for k, o, ours in P.OVR2:
    p = P.nm_app(o, 0)[0x25]
    b = P.nmfile(0x4C21 + p)
    assert len(b) == 2096 and b[:4] == b"TEX\0", (k, hex(0x4C21 + p))
    L.append("  { %d, { %s },  // %s\n    { %s } }," % (ours, ", ".join("0x%02X" % x for x in b[16:48]), k,
             ", ".join("0x%02X" % x for x in b[48:])))
L.append("};")
open(nmp("/home/devbox/work/arcade/src/photos_nm.h"), "w").write("\n".join(L) + "\n")
print("photos", [(k, ours) for k, o, ours in P.OVR2])
