# The six-man engine as word changes to the stock ROM (src/main/six_rompatch.h): the port puts them into the ROM it
# loaded, so what the runtime recompiles live (mods' hooked functions) and DMAs (overlays) is the six-man game.
#   gen_rompatch.py STOCK PORT_ROM OUT_H
# ([portable 2026-11-15] The header holds the six-man words only. The stock word beside each was the ROM's own data, which
#  nothing the game ships may hold (the user, 2026-11-14: "No game data shipped, rom(s) needed."): the program reads it from
#  the player's ROM instead, and checks the ROM is the stock one with six_rom_stock_fnv, a hash of those words -- a number.)
import sys
a = open(sys.argv[1], 'rb').read(); b = open(sys.argv[2], 'rb').read()
assert len(a) == len(b)
ch = [(o, int.from_bytes(b[o:o+4], 'big'), int.from_bytes(a[o:o+4], 'big')) for o in range(0, len(a), 4) if a[o:o+4] != b[o:o+4]]
ch = [c for c in ch if c[0] >= 0x40]           # (not the header's checksum)
fnv = 0xCBF29CE484222325                       # FNV-1a 64 over the stock words' bytes, big-endian, in table order (main.cpp)
for _, _, s in ch:
    for k in s.to_bytes(4, 'big'): fnv = ((fnv ^ k) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
L = ['// Generated by six/port/gen_rompatch.py: the six-man engine\'s ROM words (offset, six-man word).',
     '#pragma once', '#include <cstdint>',
     '// FNV-1a 64 of the stock ROM\'s words at those offsets (main.cpp six_engine_init: is the player\'s ROM the stock one?)',
     'static const uint64_t six_rom_stock_fnv = 0x%016XULL;' % fnv,
     'static const uint32_t six_rom_patch[%d][2] = {' % len(ch)]
for o, w, s in ch: L.append('    { 0x%07X, 0x%08X },' % (o, w))
L.append('};')
open(sys.argv[3], 'w').write('\n'.join(L) + '\n')
print(len(ch), 'words')