typedef uint32_t u32;
struct Mem {
    uint8_t* rdram;
    uint8_t* real = nullptr;    // (when rdram is a copy of the game's 8 MB: for what's past it)
    uint8_t* at(u32 a) const { return ((real && a >= 0x80800000u) ? real : rdram) + (a - 0x80000000u); }
    uint32_t u16_(u32 a) const { return *reinterpret_cast<uint16_t*>(at(a ^ 2u)); }
    int32_t s16_(u32 a) const { return *reinterpret_cast<int16_t*>(at(a ^ 2u)); }
    uint32_t u8_(u32 a) const { return *at(a ^ 3u); }
    void w16(u32 a, uint32_t v) const { *reinterpret_cast<uint16_t*>(at(a ^ 2u)) = uint16_t(v); }
    void w8(u32 a, uint32_t v) const { *at(a ^ 3u) = uint8_t(v); }
    u32 u32_(u32 a) const { return *reinterpret_cast<u32*>(at(a)); }
    float f32(u32 a) const { return *reinterpret_cast<float*>(at(a)); }
    double f64(u32 a) const { const uint64_t v = (uint64_t(u32_(a)) << 32) | u32_(a + 4u); double d; std::memcpy(&d, &v, 8); return d; }
    int8_t s8(u32 a) const { return *reinterpret_cast<int8_t*>(at(a ^ 3u)); }
    void wf(u32 a, float v) const { *reinterpret_cast<float*>(at(a)) = v; }
};

