// recomp_arcade_bones(slot): in the original's place
inline void bones_apply(const Mem& m, int slot) {
    build(m, slot, [&](int, u32 an, u32 world, const BoneOut& o) {
        std::memcpy(m.at(world), o.world, 64);
        m.wf(an + 0xCu, o.place[0]); m.wf(an + 0x10u, o.place[1]); m.wf(an + 0x14u, o.place[2]);
        for (u32 k = 0; k < 3u; k++) { *reinterpret_cast<u32*>(m.at(an + 0x18u + k * 4u)) = m.u32_(an + k * 4u); *reinterpret_cast<u32*>(m.at(an + 0x24u + k * 4u)) = m.u32_(an + 0xCu + k * 4u); }
    });
}
void bones_run(uint8_t* rdram, recomp_context* ctx) { bones_apply(Mem{ rdram }, _arg<0, int>(rdram, ctx)); }
// recomp_arcade_bones_check(slot), straight after the original: what it wrote against what this makes, every word
uint64_t chk_calls, chk_vals, chk_bad;
void bones_check(uint8_t* rdram, recomp_context* ctx) {
    const Mem m{ rdram };
    const int slot = _arg<0, int>(rdram, ctx);
    chk_calls++;
    bool any = false;
    build(m, slot, [&](int b, u32 an, u32 world, const BoneOut& o) {
        bool bad = std::memcmp(m.at(world), o.world, 64) != 0;
        for (u32 k = 0; k < 3u; k++) {
            if (std::memcmp(m.at(an + 0xCu + k * 4u), &o.place[k], 4)) bad = true;
            if (m.u32_(an + 0x18u + k * 4u) != m.u32_(an + k * 4u) || m.u32_(an + 0x24u + k * 4u) != m.u32_(an + 0xCu + k * 4u)) bad = true;
        }
        chk_vals += 25;
        if (bad && !any) {
            any = true; chk_bad++;
            if (chk_bad <= 8) { fprintf(stderr, "[bones] DIFFERENT: call %llu slot %d bone %d: world[0] %.6f / %.6f, [12] %.6f / %.6f\n", (unsigned long long)chk_calls, slot, b, m.f32(world), o.world[0], m.f32(world + 48u), o.world[12]); fflush(stderr); }
        }
    });
    if ((chk_calls % 4000u) == 0u) { fprintf(stderr, "[bones] %llu skeletons compared, %llu values, %llu different\n", (unsigned long long)chk_calls, (unsigned long long)chk_vals, (unsigned long long)chk_bad); fflush(stderr); }
}

// ---- func_80012130, the animation driver: each wrestler, each frame ----
// func_80010FD4: a turn about y
inline void rot_y(const Mem& m, float* o, float deg) {
    const float r = deg * m.f32(0x80047EC0u);
    const float sn = n64_sin(m, r), c = n64_cos(m, r);
    std::memset(o, 0, 64);
    o[0] = c; o[2] = -sn; o[5] = 1.0f; o[8] = sn; o[10] = c; o[15] = 1.0f;
}
// func_80036140: three angles (libultra's guRotateRPYF), its products in its order
inline void rot_rpy(const Mem& m, float* o, float a, float b, float c) {
    const float k = m.f32(0x80053790u);
    const float ra = a * k, rb = b * k, rc = c * k;
    const float sx = n64_sin(m, ra), cx = n64_cos(m, ra), sy = n64_sin(m, rb), cy = n64_cos(m, rb), sz = n64_sin(m, rc), cz = n64_cos(m, rc);
    const float cxsy = cx * sy, sxsy = sx * sy;
    std::memset(o, 0, 64);
    o[0] = cy * cz; o[1] = cy * sz; o[2] = -sy;
    o[4] = sxsy * cz - cx * sz; o[5] = sxsy * sz + cx * cz; o[6] = sx * cy;
    o[8] = cxsy * cz + sx * sz; o[9] = cxsy * sz - sx * cz; o[10] = cx * cy;
    o[15] = 1.0f;
}
// func_80038B20: a point through a matrix
inline void xform(const float* q, float x, float y, float z, float* ox, float* oy, float* oz) {
    *ox = ((q[0] * x + q[4] * y) + q[8] * z) + q[12];
    *oy = ((q[1] * x + q[5] * y) + q[9] * z) + q[13];
    *oz = ((q[2] * x + q[6] * y) + q[10] * z) + q[14];
}
inline float* fp(const Mem& m, u32 a) { return reinterpret_cast<float*>(m.at(a)); }
inline float turn_deg(int32_t x) {     // (a turn in 4096ths to degrees, whole, as the original reckons it)
    int32_t v = int32_t(u32(x) * 360u);
    if (v < 0) v += 0xFFF;
    const int32_t q = v >> 12;
    int32_t t = q < 0 ? q + 0xFFF : q;
    t = (t >> 12) << 12;
    return float(q - t);
}
// func_80011A54, a move's length: the mod's own patch of it (movex.c anim_frames), which knows the moves in the pack, past the game's table. (Reading only: on the game's own memory, even in the twin)
inline int anim_frames(const Mem& m, recomp_context* ctx, int move) {
    ctx->r4 = int64_t(move);
    func_80011A54(m.real ? m.real : m.rdram, ctx);
    return int32_t(ctx->r2);
}
uint64_t cov[10];     // (which ways through the driver the runs compared went: 0 start of a move, 1 kept the place, 2 blend, 3 step, 4 settle, 5 p5, 6 y too, 7 next key, 8 load)
enum Call { C_START = 1, C_SOUND = 2, C_LOAD = 3, C_NEXT = 4, C_TREE = 5 };   // (the ones left as they are: func_80012A8C, func_80013EB0, func_80013860, func_80012B24, and the mod's func_80002268: scene_world, gameplay.c: each matrix checked)
struct DriveArgs { int slot; u32 move, frame, pos, p5, flags; int32_t rx, rz; };
// -> false if `call` gave up
template <class C>
bool drive(const Mem& m, recomp_context* ctx, const DriveArgs& d, C&& call) {
    const int slot = d.slot;
    const u32 st = STREAM + u32(slot) * 192u;
    const u32 rec0 = ANIM + u32(slot) * 0xB24u, nodes0 = NODES + u32(slot) * 0x1810u;
    const int move = int16_t(d.move);
    uint32_t frame = d.frame & 0xFFFFu;
    const u32 flags = d.flags & 0xFFu, pos = d.pos;
    const int extra = (slot == int32_t(m.u16_(0x8009FDE0u) - 1u)) ? m.s16_(0x800A9352u) : 0;
    const float rx = d.rx != 0 ? turn_deg(int32_t(0x1000u - u32(d.rx))) : 0.0f;
    const float rz = d.rz != 0 ? turn_deg(int32_t(u32(d.rz) + 0x1000u)) : 0.0f;
    const float yaw = -float(double(int32_t(m.u32_(pos + 0xCu) + 0x800u)) * m.f64(0x80055BD8u));
    if (move != m.s16_(st + 4u)) {
        m.w16(st + 6u, 0xFFFFu);
        m.w8(SIX_80076588 + u32(slot), 0u);       // (func_80017160(slot, 0): the hands)
        frame = 0u;
    }
    bool kept = false; float keep[3] = {};
    if (frame == 0u && m.s16_(st + 6u) != 0) {
        m.w8(st + 1u, move == m.s16_(st + 4u) ? 1u : 0u);
        cov[0]++;
        if (!call(C_START, slot, move)) return false;
        if (!call(C_SOUND, slot, 0)) return false;
        const u32 v = m.u8_(st);
        m.w16(st + 4u, d.move);
        if (v == 0u) { for (u32 k = 0; k < 3u; k++) keep[k] = m.f32(rec0 + 124u + 0x54u + k * 4u); kept = true; }
    }
    bool moved = false;
    const int fr = int16_t(frame);
    if (fr != m.s16_(st + 6u)) {
        m.w16(st + 6u, frame);
        if (fr < anim_frames(m, ctx, move)) {
            const AnimView a{ anim_base(m, slot) };
            float last[3];
            if ((frame & 1u) && fr != anim_frames(m, ctx, move) - 1) {
                cov[2]++;
                if (!call(C_NEXT, slot, 0)) return false;
                std::memcpy(last, m.at(0x80069F10u), 12);
                blend_keys(m, slot, 0, a, last);
                std::memcpy(m.at(0x80069F10u), last, 12);
            } else {
                cov[3]++;
                std::memcpy(last, m.at(0x80069F10u), 12);
                step_keys(m, slot, a, last);
                std::memcpy(m.at(0x80069F10u), last, 12);
                if (fr == anim_frames(m, ctx, move) - 2) { cov[7]++; if (!call(C_NEXT, slot, 0)) return false; }
            }
            if ((flags & 2u) && m.u8_(st) == 0u && fr < 5 && m.u8_(st + 1u) == 0u) { cov[4]++; settle_keys(m, fr, int(int8_t(flags)), a); }
            if (d.p5 != 0u) {
                cov[5]++;
                const u32 r5 = rec0 + 5u * 124u;
                m.wf(r5, float(double(m.f32(d.p5)) + m.f64(0x80055BE0u)));
                m.wf(r5 + 8u, 180.0f);
                m.wf(r5 + 4u, m.f32(d.p5 + 4u));
            }
            bones_apply(m, slot);
            moved = true;
        }
    }
    float ry[16], rp[16], t[16];
    if ((flags & 1u) && kept) {
        cov[1]++;
        if (flags & 8u) cov[6]++;
        const u32 rec1 = rec0 + 124u, node = nodes0 + 0xDCu;
        rot_y(m, ry, yaw); rot_rpy(m, rp, rx, 0.0f, rz); mul(rp, ry, t);
        t[12] = m.f32(rec0 + 0xCu); t[13] = m.f32(rec0 + 0x10u); t[14] = m.f32(rec0 + 0x14u);
        const u32 parent = m.u32_(node);
        mul(fp(m, st + 0x18u), t, fp(m, parent + 0x5Cu));
        mul(fp(m, node + 0x1Cu), fp(m, parent + 0x5Cu), fp(m, node + 0x5Cu));
        xform(fp(m, node + 0x5Cu), m.f32(rec1 + 0x48u), m.f32(rec1 + 0x4Cu), m.f32(rec1 + 0x50u), fp(m, rec1 + 0x54u), fp(m, rec1 + 0x58u), fp(m, rec1 + 0x5Cu));
        const float nx = -m.f32(rec1 + 0x54u);
        m.wf(rec1 + 0x54u, nx);
        m.wf(pos, m.f32(pos) + (keep[0] - nx));
        m.wf(pos + 8u, m.f32(pos + 8u) + (keep[2] - m.f32(rec1 + 0x5Cu)));
        if (flags & 8u) m.wf(pos + 4u, m.f32(pos + 4u) + (keep[1] - m.f32(rec1 + 0x58u)));
    }
    m.wf(rec0 + 0xCu, -m.f32(pos));
    m.wf(rec0 + 0x10u, m.f32(pos + 4u) + float(extra));
    m.wf(rec0 + 0x14u, m.f32(pos + 8u));
    rot_y(m, ry, yaw); rot_rpy(m, rp, rx, 0.0f, rz); mul(rp, ry, t);
    t[12] = m.f32(rec0 + 0xCu); t[13] = m.f32(rec0 + 0x10u); t[14] = m.f32(rec0 + 0x14u);
    mul(fp(m, st + 0x18u), t, fp(m, nodes0 + 0x1Cu));
    if (!call(C_TREE, int(int32_t(nodes0)), 0)) return false;
    m.wf(rec0 + 0x78u, yaw);
    for (u32 i = 1; i < 23u; i++) {
        if (i == 20u || i == 21u) continue;
        const u32 rec = rec0 + i * 124u, node = nodes0 + i * 0xDCu;
        m.wf(rec + 0x78u, m.f32(rec + 4u) + yaw);
        const float* w = fp(m, node + 0x5Cu);
        xform(w, m.f32(rec + 0x48u), m.f32(rec + 0x4Cu), m.f32(rec + 0x50u), fp(m, rec + 0x54u), fp(m, rec + 0x58u), fp(m, rec + 0x5Cu));
        m.wf(rec + 0x54u, -m.f32(rec + 0x54u));
        xform(w, m.f32(rec + 0x60u), m.f32(rec + 0x64u), m.f32(rec + 0x68u), fp(m, rec + 0x6Cu), fp(m, rec + 0x70u), fp(m, rec + 0x74u));
        m.wf(rec + 0x6Cu, -m.f32(rec + 0x6Cu));
    }
    if (moved) { cov[8]++; if (!call(C_LOAD, slot, int16_t(frame + 1u))) return false; }
    if (m.u8_(st) != 0u) m.w8(st, 0u);
    return true;
}
inline DriveArgs read_args(const Mem& m, u32 a) {
    DriveArgs d;
    d.slot = int16_t(m.u32_(a)); d.move = m.u32_(a + 4u); d.frame = m.u32_(a + 8u); d.pos = m.u32_(a + 12u); d.p5 = m.u32_(a + 16u); d.flags = m.u32_(a + 20u); d.rx = int32_t(m.u32_(a + 24u)); d.rz = int32_t(m.u32_(a + 28u));
    return d;
}

// ---- The twin: a function proved whole against the original while the game plays. Now and then, the 8 MB as it stands as the original starts, kept. When the original has finished, the rewrite runs on the copy, and the two memories are compared, every word.
// The game is never touched. A function the rewrite still calls translated, with effects outside memory (a disk read, a sound), isn't run a second time: its writes are noted as the original makes them and put on the copy when the rewrite gets there, and the rewrite must get there in the same order, for the same reasons.
// Two kinds of difference: a word the rewrite wrote differently ("wrong"), and a word the original changed and the rewrite left ("missed": could be another thread's).
constexpr size_t RAM8 = 0x800000u;
struct Ev { int id; int a0, a1; std::vector<std::pair<u32, u32>> diff; };
struct Twin {
    std::vector<uint8_t> before, mine, pre;
    bool active = false; int depth = 0; Ev cur; std::vector<Ev> events;
    DriveArgs args{}; u32 sp = 0;
    std::chrono::steady_clock::time_point last{};
    uint64_t samples = 0, words_wrong = 0, words_missed = 0, bad_samples = 0, paths = 0, printed = 0;
    uint64_t page_wrong[128] = {}, page_missed[128] = {};     // (by 64 KB of the 8 MB)
} tw;
void twin_in(uint8_t* rdram, recomp_context* ctx) {
    if (tw.active || !getenv("WCW_TWIN")) return;
    const auto now = std::chrono::steady_clock::now();
    const Mem m0{ rdram };
    const DriveArgs a0 = read_args(m0, _arg<0, u32>(rdram, ctx));
    const u32 st0 = STREAM + u32(a0.slot) * 192u;
    const int fr0 = int16_t(a0.frame), mv0 = int16_t(a0.move);
    const bool rare = fr0 == 0 || mv0 != m0.s16_(st0 + 4u) || fr0 >= anim_frames(m0, ctx, mv0) - 3;
    if (!rare && now - tw.last < std::chrono::milliseconds(150)) return;
    tw.last = now;
    if (tw.before.empty()) { tw.before.resize(RAM8); tw.mine.resize(RAM8); tw.pre.resize(RAM8); }
    std::memcpy(tw.before.data(), rdram, RAM8);
    tw.args = a0;
    tw.sp = u32(ctx->r29);
    tw.active = true; tw.depth = 0; tw.events.clear();
}
void twin_call_in(uint8_t* rdram, recomp_context* ctx) {
    if (!tw.active) return;
    if (tw.depth++ == 0) {
        tw.cur.id = _arg<0, int>(rdram, ctx); tw.cur.a0 = tw.cur.id == C_TREE ? _arg<1, int>(rdram, ctx) : int16_t(_arg<1, int>(rdram, ctx)); tw.cur.a1 = int16_t(_arg<2, int>(rdram, ctx)); tw.cur.diff.clear();
        std::memcpy(tw.pre.data(), rdram, RAM8);
    }
}
void twin_call_out(uint8_t* rdram, recomp_context*) {
    if (!tw.active || tw.depth == 0) return;
    if (--tw.depth == 0) {
        const u32* a = reinterpret_cast<const u32*>(tw.pre.data()); const u32* b = reinterpret_cast<const u32*>(rdram);
        for (size_t i = 0; i < RAM8 / 4u; i++) if (a[i] != b[i]) tw.cur.diff.push_back({ u32(i * 4u), b[i] });
        tw.events.push_back(tw.cur);
    }
}
void twin_out(uint8_t* rdram, recomp_context* ctx) {
    if (!tw.active) return;
    tw.active = false;
    std::memcpy(tw.mine.data(), tw.before.data(), RAM8);
    const Mem m{ tw.mine.data(), rdram };
    size_t next = 0;
    bool path_ok = true;
    int bad_id = 0, bad_a0 = 0, bad_a1 = 0;
    const bool done = drive(m, ctx, tw.args, [&](int id, int a0, int a1) {
        bad_id = id; bad_a0 = a0; bad_a1 = a1;
        if (next >= tw.events.size() || tw.events[next].id != id || tw.events[next].a0 != a0 || ((id == C_START || id == C_LOAD) && tw.events[next].a1 != a1)) { path_ok = false; return false; }
        for (const auto& d : tw.events[next].diff) *reinterpret_cast<u32*>(tw.mine.data() + d.first) = d.second;
        next++;
        return true;
    });
    if (!done || !path_ok || next != tw.events.size()) {
        tw.paths++;
        if (tw.paths <= 8) { fprintf(stderr, "[twin] DIFFERENT: the path: slot %d move %d frame %u: %zu calls of %zu reached; mine last asked %d(%d,%d); the original's:", tw.args.slot, int16_t(tw.args.move), tw.args.frame & 0xFFFFu, next, tw.events.size(), bad_id, bad_a0, bad_a1); for (const auto& e : tw.events) fprintf(stderr, " %d(%d,%d)", e.id, e.a0, e.a1); fprintf(stderr, "\n"); fflush(stderr); }
        return;
    }
    tw.samples++;
    const u32 lo = (tw.sp - 0x8000u) - 0x80000000u, hi = (tw.sp + 0x40u) - 0x80000000u;   // (the stack the original used)
    const u32* B = reinterpret_cast<const u32*>(tw.before.data()); const u32* N = reinterpret_cast<const u32*>(tw.mine.data()); const u32* O = reinterpret_cast<const u32*>(rdram);
    uint64_t wrong = 0, missed = 0;
    for (size_t i = 0; i < RAM8 / 4u; i++) {
        if (N[i] == O[i]) continue;
        const u32 off = u32(i * 4u);
        if (off >= lo && off < hi) continue;
        if ((off >= 0x0C0000u && off < 0x0E0000u) || off >= 0x600000u) continue;   // (the sound's buffers, the pictures: other threads', all the time. Seen by region: nothing else differs)
        const bool w = N[i] != B[i];
        if (w) wrong++; else missed++;
        (w ? tw.page_wrong : tw.page_missed)[off >> 16]++;
        if (tw.printed < 24u) { tw.printed++; fprintf(stderr, "[twin] DIFFERENT: %s %08X: before %08X, original %08X, mine %08X (slot %d move %d frame %u, sp %08X, flags %02X, %zu calls)\n", w ? "wrong" : "missed", 0x80000000u + off, B[i], O[i], N[i], tw.args.slot, int16_t(tw.args.move), tw.args.frame & 0xFFFFu, tw.sp, tw.args.flags & 0xFFu, tw.events.size()); fflush(stderr); }
    }
    tw.words_wrong += wrong; tw.words_missed += missed; if (wrong || missed) tw.bad_samples++;
    if ((tw.samples % 100u) == 0u) { fprintf(stderr, "[twin] func_80012130: %llu whole runs compared (8 MB each), %llu with a difference: %llu words wrong, %llu missed; %llu paths different\n", (unsigned long long)tw.samples, (unsigned long long)tw.bad_samples, (unsigned long long)tw.words_wrong, (unsigned long long)tw.words_missed, (unsigned long long)tw.paths);
        fprintf(stderr, "[twin] ways through: starts %llu, kept place %llu, blends %llu, steps %llu, settles %llu, p5 %llu, with y %llu, next keys %llu, loads %llu\n", (unsigned long long)cov[0], (unsigned long long)cov[1], (unsigned long long)cov[2], (unsigned long long)cov[3], (unsigned long long)cov[4], (unsigned long long)cov[5], (unsigned long long)cov[6], (unsigned long long)cov[7], (unsigned long long)cov[8]);
        fprintf(stderr, "[twin] by region (64 KB at 0x80xx0000: wrong/missed):");
        for (int i = 0; i < 128; i++) if (tw.page_wrong[i] || tw.page_missed[i]) fprintf(stderr, " %02X:%llu/%llu", i, (unsigned long long)tw.page_wrong[i], (unsigned long long)tw.page_missed[i]);
        fprintf(stderr, "\n"); fflush(stderr); }
}
// recomp_arcade_drive(args): in the original's place
void drive_run(uint8_t* rdram, recomp_context* ctx) {
    const Mem m{ rdram };
    const DriveArgs d = read_args(m, _arg<0, u32>(rdram, ctx));
    drive(m, ctx, d, [&](int id, int a0, int a1) {
        ctx->r4 = int64_t(a0); ctx->r5 = int64_t(a1);
        switch (id) {
            case C_START: func_80012A8C(rdram, ctx); break;
            case C_SOUND: func_80013EB0(rdram, ctx); break;
            case C_LOAD: func_80013860(rdram, ctx); break;
            case C_NEXT: func_80012B24(rdram, ctx); break;
            case C_TREE: func_80002268(rdram, ctx); break;
        }
        return true;
    });
}
