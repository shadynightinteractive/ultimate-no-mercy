constexpr u32 ANIM = SIX_800A1130, NODES = SIX_80091CC0, OFFS = 0x80047ED0u, ORDER = 0x80047EF8u, PARENT = 0x80047F0Cu, PART = 0x80047F40u, BUILD = SIX_8006A268;

// the N64's sine and cosine (func_80036460, func_80034EF0): their own reductions and polynomials, in double, with their tables out of the game's memory
inline float n64_sin(const Mem& m, float x) {
    u32 bits; std::memcpy(&bits, &x, 4);
    const int e = (int32_t(bits) >> 22) & 0x1FF;
    if (e < 0xFF) {
        if (e < 0xE6) return x;
        const double d = x, x2 = d * d;
        const double r = ((m.f64(0x800563D0u) * x2 + m.f64(0x800563C8u)) * x2 + m.f64(0x800563C0u)) * x2;
        return float(d + (d * x2) * (r + m.f64(0x800563B8u)));
    }
    if (e < 0x136) {
        const double d = x, t = d * m.f64(0x800563D8u);
        const double h = t >= 0.0 ? t + m.f64(0x800563F8u) : t - m.f64(0x80056400u);
        const int32_t k = int32_t(h);
        const double dk = k;
        const double r_ = (d - dk * m.f64(0x800563E0u)) - dk * m.f64(0x800563E8u);
        const double x2 = r_ * r_;
        const double r = ((m.f64(0x800563D0u) * x2 + m.f64(0x800563C8u)) * x2 + m.f64(0x800563C0u)) * x2;
        const double o = r_ + (r_ * x2) * (r + m.f64(0x800563B8u));
        return (k & 1) ? -float(o) : float(o);
    }
    return x == x ? m.f32(0x800563F0u) : m.f32(0x80056470u);
}
inline float n64_cos(const Mem& m, float x) {
    u32 bits; std::memcpy(&bits, &x, 4);
    const int e = (int32_t(bits) >> 22) & 0x1FF;
    if (e < 0x136) {
        const float a = 0.0f < x ? x : -x;
        const double d = a, half = m.f64(0x80056338u);
        const double t = d * m.f64(0x80056318u) + half;
        const double h = t >= 0.0 ? t + half : t - half;
        const int32_t k = int32_t(h);
        const double dk = double(k) - m.f64(0x80056340u);
        const double r_ = (d - dk * m.f64(0x80056320u)) - dk * m.f64(0x80056328u);
        const double x2 = r_ * r_;
        const double r = ((m.f64(0x80056310u) * x2 + m.f64(0x80056308u)) * x2 + m.f64(0x80056300u)) * x2;
        const double o = r_ + (r_ * x2) * (r + m.f64(0x800562F8u));
        return (k & 1) ? -float(o) : float(o);
    }
    return x == x ? m.f32(0x80056330u) : m.f32(0x80056470u);
}
// func_80010E50: the rotation of the three angles (degrees: 0x80047EC0 to radians)
inline void rotation(const Mem& m, float* o, float ax, float ay, float az) {
    const float k = m.f32(0x80047EC0u);
    const float rx = ax * k, ry = ay * k, rz = az * k;
    const float sx = n64_sin(m, rx), cx = n64_cos(m, rx), sy = n64_sin(m, ry), cy = n64_cos(m, ry), sz = n64_sin(m, rz), cz = n64_cos(m, rz);
    const float czsy = cz * sy, szsy = sz * sy;
    o[0] = cz * cy; o[1] = sz * cx + czsy * sx; o[2] = sz * sx - czsy * cx; o[3] = 0.0f;
    o[4] = -sz * cy; o[5] = cz * cx - szsy * sx; o[6] = cz * sx + szsy * cx; o[7] = 0.0f;
    o[8] = sy; o[9] = -cy * sx; o[10] = cy * cx; o[11] = 0.0f;
    o[12] = 0.0f; o[13] = 0.0f; o[14] = 0.0f; o[15] = 1.0f;
}
// func_80001E08: a x b, in its order of adding
inline void mul(const float* a, const float* b, float* o) {
    for (int r = 0; r < 4; r++) for (int c = 0; c < 4; c++)
        o[r * 4 + c] = ((a[r * 4] * b[c] + a[r * 4 + 1] * b[4 + c]) + a[r * 4 + 2] * b[8 + c]) + a[r * 4 + 3] * b[12 + c];
}
struct BoneOut { float world[16], place[3]; };

// (Out: the bone's results)
template <class Out>
void build(const Mem& m, int slot, Out&& out) {
    float local[20][16], part[16];
    const u32 anim0 = ANIM + u32(slot) * 0xB24u, nodes0 = NODES + u32(slot) * 0x1810u;
    for (u32 i = 1; i < 20u; i++) {
        const int b = m.s8(ORDER + i);
        const u32 an = anim0 + u32(b) * 124u;
        const int p = m.s8(PARENT + u32(b));
        float px, py, pz;
        if (p != 0) {
            // func_80038B20: its offset from the parent, through the parent's matrix
            const float x = float(int(m.s8(OFFS + u32(b) * 2u)) - int(m.s8(OFFS + u32(p) * 2u)));
            const float y = float(int(m.s8(OFFS + u32(b) * 2u + 1u)) - int(m.s8(OFFS + u32(p) * 2u + 1u)));
            const float z = 0.0f;
            const float* q = local[p];
            px = ((q[0] * x + q[4] * y) + q[8] * z) + q[12];
            py = ((q[1] * x + q[5] * y) + q[9] * z) + q[13];
            pz = ((q[2] * x + q[6] * y) + q[10] * z) + q[14];
        } else {
            px = m.f32(an + 0xCu); py = m.f32(an + 0x10u); pz = m.f32(an + 0x14u);
        }
        float* L = local[b];
        rotation(m, L, m.f32(an), m.f32(an + 4u), m.f32(an + 8u));
        L[12] = px; L[13] = py; L[14] = pz;
        const int v = m.s8(PART + u32(b));
        const float ox = float(int(m.s8(OFFS + u32(b) * 2u))), oy = float(int(m.s8(OFFS + u32(b) * 2u + 1u)));
        if (v == -1) {
            for (int k = 0; k < 16; k++) part[k] = (k % 5 == 0) ? 1.0f : 0.0f;
            part[12] = float(-int(m.s8(OFFS + u32(b) * 2u))); part[13] = float(-int(m.s8(OFFS + u32(b) * 2u + 1u))); part[14] = 0.0f;
        } else {
            const u32 l = u32(int(m.s8(BUILD + u32(slot)))) << 2;
            for (int k = 0; k < 16; k++) part[k] = 0.0f;
            part[0] = m.f32(0x80047F54u + l); part[5] = m.f32(0x80047F68u + l); part[10] = m.f32(0x80047F7Cu + l); part[15] = 1.0f;
            part[12] = m.f32(m.u32_(0x80047FE0u + u32(v) * 4u) + l) - ox;
            part[13] = m.f32(0x80047FB8u + l) - oy;
            part[14] = m.f32(0x80047FCCu + l);
        }
        BoneOut o;
        mul(part, L, o.world);
        o.place[0] = px; o.place[1] = py; o.place[2] = pz;
        out(b, an, nodes0 + u32(b) * 0xDCu + 0x1Cu, o);
    }
}

// func_800135D0(src, rot, pos): one bone of one key of an animation: the word's three 10-bit angles; with its top bit, a place too: bit 30 a small step from the last place (three sign-and-size bytes, in half units), else a new place (11, 11, 10 bits, sign-and-size), kept as the last (0x80069F10). -> where the next bone starts
struct KeyOut { float rot[3]; bool has_pos; float pos[3]; bool new_last; u32 next; };
inline KeyOut decode_key(const Mem& m, u32 src, float* last) {
    KeyOut o{};
    u32 p = src;
    auto b = [&]() { const u32 v = *m.at(p ^ 3u); p++; return v; };
    const u32 b0 = b(), b1 = b(), b2 = b(), b3 = b();
    const u32 w = b0 << 24 | b1 << 16 | b2 << 8 | b3;
    const double ka = m.f64(0x80055BF8u);
    o.rot[0] = float(double(float(int32_t(w & 0x3FFu))) * ka);
    o.rot[1] = float(double(float(int32_t((int32_t(w) >> 10) & 0x3FF))) * ka);
    o.rot[2] = float(double(float(int32_t((int32_t(w) >> 20) & 0x3FF))) * ka);
    if (w & 0x80000000u) {
        o.has_pos = true;
        if (w & 0x40000000u) {
            const u32 c0 = b(), c1 = b(), c2 = b();
            const int x = (c0 & 0x80u) ? -int(c0 & 0x7Fu) : int(c0 & 0x7Fu), y = (c1 & 0x80u) ? -int(c1 & 0x7Fu) : int(c1 & 0x7Fu), z = (c2 & 0x80u) ? -int(c2 & 0x7Fu) : int(c2 & 0x7Fu);
            const double kp = m.f64(0x80055C00u);
            o.pos[0] = float(double(float(x)) * kp) + last[0];
            o.pos[1] = float(double(float(y)) * kp) + last[1];
            o.pos[2] = float(double(float(z)) * kp) + last[2];
        } else {
            const u32 d0 = b(), d1 = b(), d2 = b(), d3 = b();
            const u32 v = d0 << 24 | d1 << 16 | d2 << 8 | d3;
            const u32 ax = v, ay = u32(int32_t(v) >> 11), az = u32(int32_t(v) >> 22);
            const int x = (ax & 0x400u) ? -int(ax & 0x3FFu) : int(ax & 0x3FFu), y = (ay & 0x400u) ? -int(ay & 0x3FFu) : int(ay & 0x3FFu), z = (az & 0x200u) ? -int(az & 0x1FFu) : int(az & 0x1FFu);
            o.pos[0] = float(x); o.pos[1] = float(y); o.pos[2] = float(z);
            o.new_last = true;
            last[0] = o.pos[0]; last[1] = o.pos[1]; last[2] = o.pos[2];
        }
    }
    o.next = p;
    return o;
}
// recomp_arcade_key_check(src, rot, pos), straight after the original: what it wrote against what this makes. (A step's place is checked against the last place, which it didn't change)
uint64_t key_calls, key_bad;
void key_check(uint8_t* rdram, recomp_context* ctx) {
    const Mem m{ rdram };
    const u32 src = _arg<0, u32>(rdram, ctx), rot = _arg<1, u32>(rdram, ctx), pos = _arg<2, u32>(rdram, ctx);
    float last[3]; std::memcpy(last, m.at(0x80069F10u), 12);
    const KeyOut o = decode_key(m, src, last);
    bool bad = std::memcmp(m.at(rot), o.rot, 12) != 0;
    if (o.has_pos && std::memcmp(m.at(pos), o.pos, 12) != 0) bad = true;
    if (o.new_last && std::memcmp(m.at(0x80069F10u), o.pos, 12) != 0) bad = true;
    key_calls++;
    if (bad) { key_bad++; if (key_bad <= 8) { fprintf(stderr, "[key] DIFFERENT: call %llu src %08X: rot %.4f / %.4f, pos %.4f / %.4f\n", (unsigned long long)key_calls, src, m.f32(rot), o.rot[0], m.f32(pos), o.pos[0]); fflush(stderr); } }
    if ((key_calls % 200000u) == 0u) { fprintf(stderr, "[key] %llu keys compared, %llu different\n", (unsigned long long)key_calls, (unsigned long long)key_bad); fflush(stderr); }
}
// recomp_arcade_key(src, rot, pos) -> next: in the original's place
void key_run(uint8_t* rdram, recomp_context* ctx) {
    const Mem m{ rdram };
    const u32 src = _arg<0, u32>(rdram, ctx), rot = _arg<1, u32>(rdram, ctx), pos = _arg<2, u32>(rdram, ctx);
    float last[3]; std::memcpy(last, m.at(0x80069F10u), 12);
    const KeyOut o = decode_key(m, src, last);
    std::memcpy(m.at(rot), o.rot, 12);
    if (o.has_pos) std::memcpy(m.at(pos), o.pos, 12);
    if (o.new_last) std::memcpy(m.at(0x80069F10u), o.pos, 12);
    ctx->r2 = int32_t(o.next);
}

// func_80011270: an angle brought back into -180 .. 180, the N64's way, step by step
inline float wrap_angle(const Mem& m, float x) {
    double d = x;
    float r = x;
    if (0.0 <= d) {
        const double top = m.f64(0x80055BA0u);
        if (top < d) {
            const double turn = m.f64(0x80055BA8u);
            double f = d - turn;
            for (;;) { r = float(f); f = r; if (top < f) f -= turn; else break; }
        }
    } else {
        const double bottom = m.f64(0x80055BB0u);
        if (d <= bottom) {
            const double turn = m.f64(0x80055BB8u);
            double f = double(r) + turn;
            for (;;) { r = float(f); f = r; if (f <= bottom) f += turn; else break; }
        }
    }
    return r;
}
inline float abs_n64(float x) { return double(x) < 0.0 ? -x : x; }     // (func_8000567C)

constexpr u32 STREAM = SIX_80069F20;        // (per slot, 192 bytes: + 2 which of the two key buffers, + 8 where each has got to)
inline u32 key_source(const Mem& m, int slot) {
    const u32 s_ = u32(slot) * 192u;
    return STREAM + s_ + 8u + u32(*m.at((STREAM + s_ + 2u) ^ 3u)) * 4u;
}
// a slot's 20 bones' animation records, on the side or in place
struct AnimView {
    uint8_t* base;       // (the slot's records, bone 0's)
    float get(u32 b, u32 off) const { return *reinterpret_cast<float*>(base + b * 124u + off); }
    void set(u32 b, u32 off, float v) const { *reinterpret_cast<float*>(base + b * 124u + off) = v; }
};
// func_80013234(slot): the next key, straight onto the bones. (rot at + 0, place at + 0xC)
inline void step_keys(const Mem& m, int slot, const AnimView& a, float* last) {
    u32 src = m.u32_(key_source(m, slot));
    for (u32 i = 1; i < 20u; i++) {
        const KeyOut o = decode_key(m, src, last);
        for (u32 k = 0; k < 3u; k++) a.set(i, k * 4u, o.rot[k]);
        if (o.has_pos) for (u32 k = 0; k < 3u; k++) a.set(i, 0xCu + k * 4u, o.pos[k]);
        src = o.next;
    }
}
// func_800132D8(slot, n), after func_80012B24: the next key, a share of the way (by n % 3, 0x8004800C): the turn taken the short way round
inline void blend_keys(const Mem& m, int slot, int n, const AnimView& a, float* last) {
    const int f_ = int16_t(n) % 3;
    const float share = m.f32(0x8004800Cu + u32(int32_t(int16_t(f_))) * 4u);
    float rot[20][3], pos[20][3];
    std::memset(pos, 0, sizeof pos); std::memset(rot, 0, sizeof rot);
    u32 src = m.u32_(key_source(m, slot));
    for (u32 i = 1; i < 20u; i++) {
        const KeyOut o = decode_key(m, src, last);
        std::memcpy(rot[i], o.rot, 12);
        if (o.has_pos) std::memcpy(pos[i], o.pos, 12);
        src = o.next;
    }
    const double limit = m.f64(0x80055BF0u);
    const float half = 180.0f;
    for (u32 i = 1; i < 20u; i++) {
        const int b = m.s8(ORDER + i);
        if (m.s8(PARENT + u32(b)) == 0) {
            for (u32 k = 0; k < 3u; k++) {
                const float c = a.get(u32(b), 0xCu + k * 4u);
                a.set(u32(b), 0xCu + k * 4u, c + (pos[b][k] - c) * share);
            }
        }
        float* r = rot[b];
        r[0] = wrap_angle(m, r[0] - a.get(u32(b), 0u));
        r[1] = wrap_angle(m, r[1] - a.get(u32(b), 4u));
        r[2] = wrap_angle(m, r[2] - a.get(u32(b), 8u));
        if (limit < double(abs_n64(r[0])) || limit < double(abs_n64(r[2]))) {
            r[0] = wrap_angle(m, r[0] + half);
            r[2] = wrap_angle(m, r[2] + half);
        }
        for (u32 k = 0; k < 3u; k++) a.set(u32(b), k * 4u, a.get(u32(b), k * 4u) + r[k] * share);
    }
}
// func_80012F48(slot, n, flags): easing into a new move, over its first frames: the bones a share of the way (by n, 0x80047FF8) from where they are to the new key (kept at + 0x18 angles, + 0x24 place). On its first frame, unless flags & 4, the key's place is made relative to its first bone's: x and z, and y too with flags & 8
inline void settle_keys(const Mem& m, int n, int flags, const AnimView& a) {
    if (n == 0 && !(flags & 4)) {
        const float bx = a.get(1u, 0x24u), bz = a.get(1u, 0x2Cu);
        for (u32 i = 1; i < 20u; i++) { a.set(i, 0x24u, a.get(i, 0x24u) - bx); a.set(i, 0x2Cu, a.get(i, 0x2Cu) - bz); }
        if (flags & 8) {
            const float by = a.get(1u, 0x28u);
            for (u32 i = 1; i < 20u; i++) a.set(i, 0x28u, a.get(i, 0x28u) - by);
        }
    }
    const float share = m.f32(0x80047FF8u + u32(n) * 4u);
    const double limit = m.f64(0x80055BE8u);
    const float half = 180.0f;
    for (u32 i = 1; i < 20u; i++) {
        if (m.s8(PARENT + i) == 0) {
            for (u32 k = 0; k < 3u; k++) {
                const float c = a.get(i, 0xCu + k * 4u);
                a.set(i, 0xCu + k * 4u, c + (a.get(i, 0x24u + k * 4u) - c) * share);
            }
        }
        for (u32 k = 0; k < 3u; k++) a.set(i, 0x18u + k * 4u, wrap_angle(m, a.get(i, 0x18u + k * 4u) - a.get(i, k * 4u)));
        if (limit < double(abs_n64(a.get(i, 0x18u))) && limit < double(abs_n64(a.get(i, 0x20u)))) {
            a.set(i, 0x18u, wrap_angle(m, a.get(i, 0x18u) + half));
            a.set(i, 0x20u, wrap_angle(m, a.get(i, 0x20u) + half));
        }
        for (u32 k = 0; k < 3u; k++) a.set(i, k * 4u, a.get(i, k * 4u) + a.get(i, 0x18u + k * 4u) * share);
    }
}
static uint8_t shadow[8][2480]; static float shadow_last[8][3];
inline uint8_t* anim_base(const Mem& m, int slot) { return m.at(ANIM + u32(slot) * 0xB24u); }
// recomp_arcade_anim_snap(slot): before the original runs: what it starts from
void anim_snap(uint8_t* rdram, recomp_context* ctx) {
    const Mem m{ rdram };
    const int slot = _arg<0, int>(rdram, ctx);
    if (slot < 0 || slot >= 8) return;
    std::memcpy(shadow[slot], anim_base(m, slot), 2480);
    std::memcpy(shadow_last[slot], m.at(0x80069F10u), 12);
}
// recomp_arcade_anim_check(slot, n): after: n < 0: func_80013234's; else func_800132D8's
uint64_t an_calls, an_bad;
void anim_check(uint8_t* rdram, recomp_context* ctx) {
    const Mem m{ rdram };
    const int slot = _arg<0, int>(rdram, ctx), n = _arg<1, int>(rdram, ctx);
    if (slot < 0 || slot >= 8) return;
    AnimView a{ shadow[slot] };
    float last[3]; std::memcpy(last, shadow_last[slot], 12);
    const int flags = _arg<2, int>(rdram, ctx);
    if (flags >= 0) settle_keys(m, int16_t(n), flags, a);
    else if (n < 0) step_keys(m, slot, a, last); else blend_keys(m, slot, n, a, last);
    an_calls++;
    bool bad = false; u32 where = 0;
    for (u32 b = 1; b < 20u && !bad; b++) for (u32 o = 0; o < 0x30u; o += 4u)
        if (std::memcmp(shadow[slot] + b * 124u + o, anim_base(m, slot) + b * 124u + o, 4)) { bad = true; where = b << 8 | o; break; }
    if (bad) { an_bad++; if (an_bad <= 8) { fprintf(stderr, "[anim] DIFFERENT: call %llu slot %d n %d at %x: mine %.5f theirs %.5f\n", (unsigned long long)an_calls, slot, n, where, *reinterpret_cast<float*>(shadow[slot] + (where >> 8) * 124u + (where & 255u)), *reinterpret_cast<float*>(anim_base(m, slot) + (where >> 8) * 124u + (where & 255u))); fflush(stderr); } }
    if ((an_calls % 4000u) == 0u) { fprintf(stderr, "[anim] %llu frames of animation compared, %llu different\n", (unsigned long long)an_calls, (unsigned long long)an_bad); fflush(stderr); }
}
