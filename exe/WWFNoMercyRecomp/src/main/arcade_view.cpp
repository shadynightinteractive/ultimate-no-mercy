// an N64 fixed-point matrix (item + 0x38 + slot * 64): the frame's world x view x projection: points are row vectors
static void fixed_matrix(const Mem& m, u32 a, float* o) {
    for (int i = 0; i < 8; i++) {
        const u32 hi = m.u32_(a + 4u * i), lo = m.u32_(a + 32u + 4u * i);
        o[i * 2] = int32_t((hi & 0xFFFF0000u) | (lo >> 16)) / 65536.0f;
        o[i * 2 + 1] = int32_t((hi << 16) | (lo & 0xFFFFu)) / 65536.0f;
    }
}
static bool inverse4(const float* m, float* o) {
    float a[4][8];
    for (int r = 0; r < 4; r++) for (int c = 0; c < 4; c++) { a[r][c] = m[r * 4 + c]; a[r][c + 4] = r == c; }
    for (int c = 0; c < 4; c++) {
        int p = c; for (int r = c + 1; r < 4; r++) if (std::fabs(a[r][c]) > std::fabs(a[p][c])) p = r;
        if (std::fabs(a[p][c]) < 1e-9f) return false;
        if (p != c) for (int k = 0; k < 8; k++) std::swap(a[p][k], a[c][k]);
        const float d = a[c][c]; for (int k = 0; k < 8; k++) a[c][k] /= d;
        for (int r = 0; r < 4; r++) if (r != c) { const float f = a[r][c]; for (int k = 0; k < 8; k++) a[r][k] -= f * a[c][k]; }
    }
    for (int r = 0; r < 4; r++) for (int c = 0; c < 4; c++) o[r * 4 + c] = a[r][c + 4];
    return true;
}

