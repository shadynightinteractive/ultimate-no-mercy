    { uint64_t h = 0xCBF29CE484222325ull; const unsigned char* b = reinterpret_cast<const unsigned char*>(mvp); for (int i = 0; i < 64; i++) { h ^= b[i]; h *= 0x100000001B3ull; } s.mhash = h; }
    if (world_depth_on() && layer_of_.count(s.mhash)) s.state_new = true;     // (a matrix already drawn with this frame: a draw of its own, a later layer)
