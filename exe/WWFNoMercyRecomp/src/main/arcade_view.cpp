static inline u32 rgba5551(u32 v) { const u32 r = ((v >> 11) & 31) * 255 / 31, g = ((v >> 6) & 31) * 255 / 31, b = ((v >> 1) & 31) * 255 / 31; return r | g << 8 | b << 16 | ((v & 1) ? 255u : 0u) << 24; }

// ---- a native Titantron video (2026-11-10) -------------------------------------------------------------------------------
// While the exe plays a wrestler's video file (arcade_media.cpp), the mod still draws the game's own video frame into the
// Titantron's picture as it always did (tron.c video_pass: a black placeholder frame at TRON_FRAME, as two rectangles, the
// frame's top half and its bottom half). Those two rectangles are kept, and given texture -4: the decoded picture, at the
// size it was decoded, in place of the 64 x 64 frame. So the arena's truss, the panels and where the video sits on the
// screen are exactly the game's.
// Which half of the frame a rectangle's texture is: 0 the top, 1 the bottom; -1: not the video frame.
static int native_video_half(u32 tex_img) {
    static const u32 TEXELS[2] = { 0x806E8100u + 16u + 512u, 0x806EA000u + 16u + 512u };     // (TRON_FRAME, TRON_FRAME_B: header, palette, then 64 x 64)
    for (u32 frame : TEXELS) { if (tex_img == frame) return 0; if (tex_img == frame + 2048u) return 1; }
    return -1;
}
// How a native video lies on the screen: THE ONE PLACE that decides it. It fills the screen's part and is cropped evenly
// at the middle, never stretched and never with bars (the user, 2026-11-10: as the stock Titantrons fill the screen; a
// 16:9 file loses about a tenth of its height). A fit / fill choice, if one is wanted later, goes here.
// shape: the part's width over its height; video: the picture's. -> the part of the picture shown, 0..1: u0, v0, u1, v1.
static void native_video_crop(float shape, float video, float* uv) {
    uv[0] = 0; uv[1] = 0; uv[2] = 1; uv[3] = 1;
    if (shape <= 0 || video <= 0) return;
    if (video < shape) { const float keep = video / shape; uv[1] = 0.5f - 0.5f * keep; uv[3] = 0.5f + 0.5f * keep; }      // (taller than the screen: top and bottom go)
    else { const float keep = shape / video; uv[0] = 0.5f - 0.5f * keep; uv[2] = 0.5f + 0.5f * keep; }                     // (wider: the sides go)
}

static int texture_of(const Mem& m, const St& s) {
    const Tile& t = s.tiles[s.tile];
    const u32 img = s.tex_img;
    if (!img) return -2;
    if (img == 0x806C0000u) return -1;                       // (the Titantron's picture: the target of its own)
    if (img == 0x806C4000u) return -3;                       // (the same picture cut to a sign's own shape: tron.c mask_compose: its target too)
    for (int man = 0; man < HD_MEN; man++) {
        if (hd_pack_[man] && img >= hd_pack_[man] && img < hd_pack_[man] + 6u * HD_TEX_W * HD_TEX_H * 2u) return man * 6 + int((img - hd_pack_[man]) / (HD_TEX_W * HD_TEX_H * 2u));
    }
    const int w = t.w, h = t.h;
    if (w <= 0 || h <= 0 || w > 2048 || h > 2048) return -2;
    const u32 bpp = 4u << t.siz;
    // (the picture's row in memory: a tile load's from the image's own width, a block's from the tile's line)
    u32 lb;
    if (s.tex_by_tile && s.tex_imgw) lb = (s.tex_imgw * (4u << s.tex_siz)) / 8u;
    else lb = t.line ? t.line * 8u : std::max<u32>(1u, (s.tex_imgw * bpp) / 8u);
    const u32 base = img + s.tex_oy * lb + (s.tex_ox * (4u << s.tex_siz)) / 8u;
    const u32 bytes = lb * h;
    if (base + bytes >= 0xA0000000u || base < 0x80000000u) return -2;
    const u32 img_ = base;
    // (what it is: all of its texels, every time: an animated picture changes in place)
    const u32 tt_ = (s.other_h >> 14) & 3u;
    const uint64_t key[3] = { uint64_t(img_) | uint64_t(lb) << 32, uint64_t(t.fmt | t.siz << 4 | w << 8 | h << 20), uint64_t(tt_) | uint64_t(t.pal) << 8 };
    uint64_t hsh = XXH3_64bits(key, sizeof key);
    // (the palette on, in the other modes, and it's what the texels mean, whatever the tile's format says: 4 and 8 bits are indices: the THQ's logo is "IA8". Its entries RGBA 5551, or, the other setting, intensity and alpha)
    const u32 tt = (s.other_h >> 14) & 3u;
    const bool paletted = tt >= 2u && t.siz <= 2u;
    const u32 pal_at = t.siz == 0u ? t.pal << 4 : 0u, pal_n = t.siz == 0u ? 16u : 256u;
    hsh = XXH3_64bits_withSeed(m.at(img_ & ~3u), bytes & ~3u, hsh);
    if (paletted) {
        if (pal_at + pal_n <= 256u) hsh = XXH3_64bits_withSeed(pal_mem_ + pal_at, size_t(pal_n) * 2u, hsh);
        else for (u32 i = 0; i < pal_n; i++) { const uint16_t e = pal_mem_[(pal_at + i) & 255u]; hsh = XXH3_64bits_withSeed(&e, 2u, hsh); }
    }
    auto it = tex_ids_.find(hsh);
    if (it != tex_ids_.end()) { if (size_t(it->second) < last_use_.size()) last_use_[it->second] = frame_no_; return it->second; }
    NewTex n; n.id = next_tex_++;
    if (last_use_.size() <= size_t(n.id)) last_use_.resize(size_t(n.id) + 256, 0);
    last_use_[n.id] = frame_no_; n.w = w; n.h = h; n.rgba.resize(size_t(w) * h * 4);
    u32* out = reinterpret_cast<u32*>(n.rgba.data());
    for (int y = 0; y < h; y++) {
        const u32 row = img_ + y * lb;
        for (int x = 0; x < w; x++) {
            u32 c = 0xFFFF00FFu, v = 0;
            if (t.siz == 0) { const u32 b = m.u8_(row + x / 2); v = (x & 1) ? (b & 15) : (b >> 4); }
            else if (t.siz == 1) v = m.u8_(row + x);
            else if (t.siz == 2) v = m.u16(row + x * 2);
            if (paletted) {
                const u32 e = pal_mem_[(pal_at + (t.siz == 2u ? v >> 8 : v)) & 255u];      // (16 bits: the texel's first byte, as the hardware reads it)
                c = tt == 3u ? ((e >> 8) | (e >> 8) << 8 | (e >> 8) << 16 | (e & 255u) << 24) : rgba5551(e);
            }
            else if (t.fmt == 2) c = v | v << 8 | v << 16 | 255u << 24;
            else if (t.fmt == 0 && t.siz == 2) c = rgba5551(v);
            else if (t.fmt == 0 && t.siz == 3) { const u32 a = row + x * 4; c = m.u8_(a) | m.u8_(a + 1) << 8 | m.u8_(a + 2) << 16 | m.u8_(a + 3) << 24; }
            else if (t.fmt == 3 && t.siz == 0) { const u32 i = (v >> 1) * 255 / 7; c = i | i << 8 | i << 16 | ((v & 1) ? 255u : 0u) << 24; }
            else if (t.fmt == 3 && t.siz == 1) { const u32 i = (v >> 4) * 17; c = i | i << 8 | i << 16 | ((v & 15) * 17) << 24; }
            else if (t.fmt == 3 && t.siz == 2) { const u32 i = v >> 8; c = i | i << 8 | i << 16 | (v & 255) << 24; }
            else if (t.fmt == 4 && t.siz == 0) { const u32 i = v * 17; c = i | i << 8 | i << 16 | i << 24; }
            else if (t.fmt == 4 && t.siz == 1) { c = v | v << 8 | v << 16 | v << 24; }
            out[y * w + x] = c;
        }
    }
    // A texture pack can replace it: arcade_texpacks.cpp. Its name is from its pixels and size alone, not where it's kept.
    {
        const uint64_t size_seed = uint64_t(w) << 32 | uint32_t(h);
        arcade_texpacks_apply(XXH3_64bits_withSeed(n.rgba.data(), n.rgba.size(), size_seed), n.w, n.h, n.rgba);
    }
    tex_ids_[hsh] = n.id;
    const int id = n.id;
    fresh_tex_.push_back(std::move(n));
    return id;
}

// ---- taking matrices apart, and putting them back ------------------------------------------------------------------
static float det3(const double a[3][3]) { return float(a[0][0] * (a[1][1] * a[2][2] - a[1][2] * a[2][1]) - a[0][1] * (a[1][0] * a[2][2] - a[1][2] * a[2][0]) + a[0][2] * (a[1][0] * a[2][1] - a[1][1] * a[2][0])); }
static void quat_of(const double r[3][3], float* q) {
    const double tr = r[0][0] + r[1][1] + r[2][2];
    double w, x, y, z;
    if (tr > 0) { const double k = std::sqrt(tr + 1.0) * 2; w = 0.25 * k; x = (r[2][1] - r[1][2]) / k; y = (r[0][2] - r[2][0]) / k; z = (r[1][0] - r[0][1]) / k; }
    else if (r[0][0] > r[1][1] && r[0][0] > r[2][2]) { const double k = std::sqrt(1.0 + r[0][0] - r[1][1] - r[2][2]) * 2; w = (r[2][1] - r[1][2]) / k; x = 0.25 * k; y = (r[0][1] + r[1][0]) / k; z = (r[0][2] + r[2][0]) / k; }
    else if (r[1][1] > r[2][2]) { const double k = std::sqrt(1.0 + r[1][1] - r[0][0] - r[2][2]) * 2; w = (r[0][2] - r[2][0]) / k; x = (r[0][1] + r[1][0]) / k; y = 0.25 * k; z = (r[1][2] + r[2][1]) / k; }
    else { const double k = std::sqrt(1.0 + r[2][2] - r[0][0] - r[1][1]) * 2; w = (r[1][0] - r[0][1]) / k; x = (r[0][2] + r[2][0]) / k; y = (r[1][2] + r[2][1]) / k; z = 0.25 * k; }
    q[0] = float(x); q[1] = float(y); q[2] = float(z); q[3] = float(w);
}
// [visual 2026-11-19] a plain affine matrix (what take_apart asks first): its last column 0, 0, 0, 1
static bool affine(const float* m) { return std::fabs(m[3]) <= 1e-3f && std::fabs(m[7]) <= 1e-3f && std::fabs(m[11]) <= 1e-3f && std::fabs(m[15] - 1.0f) <= 1e-3f; }
// the matrix's top 3 x 3 = sign x stretch x turn (its polar decomposition: the turn found by Higham's iteration), its last row the place. -> false if it can't be: flat, or not a plain affine matrix
static bool take_apart(const float* m, Dec& d) {
    if (std::fabs(m[3]) > 1e-3f || std::fabs(m[7]) > 1e-3f || std::fabs(m[11]) > 1e-3f || std::fabs(m[15] - 1.0f) > 1e-3f) return false;
    double A[3][3] = { { m[0], m[1], m[2] }, { m[4], m[5], m[6] }, { m[8], m[9], m[10] } };
    double dt = det3(A);
    if (std::fabs(dt) < 1e-9) return false;
    d.sign = dt < 0 ? -1.0f : 1.0f;
    if (dt < 0) for (auto& r : A) for (double& v : r) v = -v;
    double Q[3][3]; std::memcpy(Q, A, sizeof Q);
    for (int it = 0; it < 12; it++) {
        const double dq = Q[0][0] * (Q[1][1] * Q[2][2] - Q[1][2] * Q[2][1]) - Q[0][1] * (Q[1][0] * Q[2][2] - Q[1][2] * Q[2][0]) + Q[0][2] * (Q[1][0] * Q[2][1] - Q[1][1] * Q[2][0]);
        if (std::fabs(dq) < 1e-12) return false;
        const double C[3][3] = {
            { (Q[1][1] * Q[2][2] - Q[1][2] * Q[2][1]) / dq, (Q[1][2] * Q[2][0] - Q[1][0] * Q[2][2]) / dq, (Q[1][0] * Q[2][1] - Q[1][1] * Q[2][0]) / dq },
            { (Q[0][2] * Q[2][1] - Q[0][1] * Q[2][2]) / dq, (Q[0][0] * Q[2][2] - Q[0][2] * Q[2][0]) / dq, (Q[0][1] * Q[2][0] - Q[0][0] * Q[2][1]) / dq },
            { (Q[0][1] * Q[1][2] - Q[0][2] * Q[1][1]) / dq, (Q[0][2] * Q[1][0] - Q[0][0] * Q[1][2]) / dq, (Q[0][0] * Q[1][1] - Q[0][1] * Q[1][0]) / dq } };
        double ch = 0;
        for (int r = 0; r < 3; r++) for (int c = 0; c < 3; c++) { const double n = 0.5 * (Q[r][c] + C[r][c]); ch += std::fabs(n - Q[r][c]); Q[r][c] = n; }
        if (ch < 1e-10) break;
    }
    double S[3][3];
    for (int r = 0; r < 3; r++) for (int c = 0; c < 3; c++) S[r][c] = A[r][0] * Q[c][0] + A[r][1] * Q[c][1] + A[r][2] * Q[c][2];
    d.s[0] = float(S[0][0]); d.s[1] = float(S[1][1]); d.s[2] = float(S[2][2]); d.s[3] = float(0.5 * (S[0][1] + S[1][0])); d.s[4] = float(0.5 * (S[0][2] + S[2][0])); d.s[5] = float(0.5 * (S[1][2] + S[2][1]));
    quat_of(Q, d.q);
    d.t[0] = m[12]; d.t[1] = m[13]; d.t[2] = m[14];
    return true;
}
void put_together(const Dec& a, const Dec& b, float k, float* o) {
    float dot = a.q[0] * b.q[0] + a.q[1] * b.q[1] + a.q[2] * b.q[2] + a.q[3] * b.q[3];
    const float sg = dot < 0 ? -1.0f : 1.0f; dot *= sg;
    float ka = 1.0f - k, kb = k * sg;
    if (dot < 0.9995f) { const float th = std::acos(dot), sn = std::sin(th); ka = std::sin((1.0f - k) * th) / sn; kb = sg * std::sin(k * th) / sn; }
    float x = ka * a.q[0] + kb * b.q[0], y = ka * a.q[1] + kb * b.q[1], z = ka * a.q[2] + kb * b.q[2], w = ka * a.q[3] + kb * b.q[3];
    const float n = 1.0f / std::sqrt(x * x + y * y + z * z + w * w); x *= n; y *= n; z *= n; w *= n;
    const float Rm[3][3] = { { 1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w) }, { 2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w) }, { 2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y) } };
    float sv[6]; for (int i = 0; i < 6; i++) sv[i] = a.s[i] + (b.s[i] - a.s[i]) * k;
    const float Sm[3][3] = { { sv[0], sv[3], sv[4] }, { sv[3], sv[1], sv[5] }, { sv[4], sv[5], sv[2] } };
    for (int r = 0; r < 3; r++) { for (int c = 0; c < 3; c++) o[r * 4 + c] = b.sign * (Sm[r][0] * Rm[0][c] + Sm[r][1] * Rm[1][c] + Sm[r][2] * Rm[2][c]); o[r * 4 + 3] = 0.0f; }
    o[12] = a.t[0] + (b.t[0] - a.t[0]) * k; o[13] = a.t[1] + (b.t[1] - a.t[1]) * k; o[14] = a.t[2] + (b.t[2] - a.t[2]) * k; o[15] = 1.0f;
}

