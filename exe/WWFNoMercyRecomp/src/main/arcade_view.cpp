double clock_ms(uint64_t t) { static const uint64_t t0 = arcade::platform::ticks(); static const double f = double(arcade::platform::ticks_per_second()); return double(int64_t(t - t0)) * 1000.0 / f; }
// [visual 2026-11-19] when the game's retrace vi came, on clock_ms's clock: the game's clock (ultramodern timer.cpp: 46,875,000 ticks a
// second of its own, faster in the tests' fast-forward) counts a retrace each 1/60 s of it
static double retrace_ms(uint64_t vi, uint64_t now_ticks) {
    const double speed = double(std::max<uint32_t>(1u, ultramodern::get_speed_multiplier()));
    return clock_ms(now_ticks) - (double(ultramodern::game_ticks_now()) - double(vi) * (46875000.0 / 60.0)) / 46875.0 / speed;
}
// Smooth Motion's clock (arcade_view_shared.h)
static constexpr uint64_t PACE_GAP = 8;     // (more retraces than this between two updates: a pause -- a load, a menu -- not motion: no blend)
static constexpr double PACE_HOLD = 150.0;  // (ms an update in hand may wait past its hand-over: a normal one waits under a refresh and a few ms)
bool Pace::due(const Frame& cur, bool have, const Frame& next, double now) const {
    if (!have || lag < 0.0) return true;
    if (next.vi_prev != cur.vi || next.vi <= next.vi_prev || next.vi - next.vi_prev > PACE_GAP) return true;     // (not the next one in line: no waiting)
    if (now - clock_ms(next.t_hand) > PACE_HOLD) return true;     // (never kept waiting long: whatever the clock says, the picture can't stand still on it)
    return now - lag >= cur.w_vi;
}
void Pace::took(const Frame& f, double refresh_ms, double now) {
    // (what this update needed: from the moment its blend begins -- its last update's retrace -- to its hand-over, and a picture to be found in)
    // (the start, or after a pause -- a menu, a load: its last update long gone -- this one shown as it is from now, its own retrace the
    //  moment. 2026-11-19, the final entrance run: anchored on the LAST update's retrace, seconds before, the lag came out seconds long
    //  and the picture stood still on one update)
    if (lag < 0.0 || f.vi <= f.vi_prev || f.vi - f.vi_prev > PACE_GAP) { lag = std::max(now - f.w_vi, 0.0); shown = f.w_vi; return; }
    const double need = clock_ms(f.t_hand) - f.w_vi_prev + refresh_ms + 2.0;
    if (need > lag || need < lag - 50.0) lag = need;  // (a late one: the lag grows at once -- the picture holds rather than jump; or far more lag than needed: back at once)
    else lag -= std::min(lag - need, 0.05);           // (then comes back slowly: 1.5 ms a second, the game's motion 0.15% quicker meanwhile)
}
float Pace::k(const Frame& f, double now) {
    const double m = std::max(now - lag, shown);
    shown = m;
    if (f.vi <= f.vi_prev || f.vi - f.vi_prev > PACE_GAP || f.w_vi <= f.w_vi_prev) return 1.0f;
    const double k = (m - f.w_vi_prev) / (f.w_vi - f.w_vi_prev);
    return float(k < 0.0 ? 0.0 : k > 1.0 ? 1.0 : k);
}
