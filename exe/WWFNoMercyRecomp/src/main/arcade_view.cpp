static void load_verts(const Mem& m, Frame& f, St& s, u32 a, u32 first, u32 cnt) {
    const size_t base = f.v.size();
    f.v.resize(base + cnt);
    V* out = f.v.data() + base;
    const float* pp = nullptr;
    if (s.key) {
        const uint64_t lk = s.key * 0x100000001B3ULL + s.load_ord++;
        auto it = load_prev_.find(lk);
        if (it != load_prev_.end() && it->second.count == cnt) pp = pos_prev_.data() + size_t(it->second.start) * 3;
        f.loads_keyed++; if (pp) f.loads_matched++; else f.verts_unmatched += cnt;     // [visual 2026-11-19] (the trace)
        load_cur_[lk] = Load{ u32(pos_cur_.size() / 3), cnt };
    }
    if (!s.key && s.target == 0 && s.persp) { f.loads_plain++; f.verts_plain += cnt; }     // [visual 2026-11-19] (the trace)
    const size_t ps = pos_cur_.size();
    if (s.key) pos_cur_.resize(ps + size_t(cnt) * 3);
    for (u32 i = 0; i < cnt; i++) {
        const u32 p = a + i * 16u;
        const u32 w0 = m.u32_(p), w1 = m.u32_(p + 4u), w2 = m.u32_(p + 8u), w3 = m.u32_(p + 12u);
        V& v = out[i];
        v.x = float(int16_t(w0 >> 16)); v.y = float(int16_t(w0 & 0xFFFFu)); v.z = float(int16_t(w1 >> 16));
        if (pp) { v.px = pp[i * 3]; v.py = pp[i * 3 + 1]; v.pz = pp[i * 3 + 2]; } else { v.px = v.x; v.py = v.y; v.pz = v.z; }
        if (s.key) { pos_cur_[ps + i * 3] = v.x; pos_cur_[ps + i * 3 + 1] = v.y; pos_cur_[ps + i * 3 + 2] = v.z; }
        v.s = int16_t(w2 >> 16) / 32.0f; v.t = int16_t(w2 & 0xFFFFu) / 32.0f;
        v.r = u8(w3 >> 24); v.g = u8(w3 >> 16); v.b = u8(w3 >> 8); v.a = u8(w3); v.xf = s.xf;
        if (first + i < 128u) s.slot_v[first + i] = int(base + i);
    }
}
