// a triangle's plane, by its matrix: its normal (one way round: the largest part positive) to 1/256 and its distance to a unit.
// false for a triangle of no area (the lists' EMPTY pieces)
static bool plane_key(const V& a, const V& b, const V& c, uint64_t mhash, uint64_t& key) {
    const double ux = b.x - a.x, uy = b.y - a.y, uz = b.z - a.z, vx = c.x - a.x, vy = c.y - a.y, vz = c.z - a.z;
    double nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
    const double len = std::sqrt(nx * nx + ny * ny + nz * nz);
    if (len < 1e-6) return false;
    nx /= len; ny /= len; nz /= len;
    const double big = std::fabs(nx) >= std::fabs(ny) && std::fabs(nx) >= std::fabs(nz) ? nx : std::fabs(ny) >= std::fabs(nz) ? ny : nz;
    if (big < 0) { nx = -nx; ny = -ny; nz = -nz; }
    const double d = nx * a.x + ny * a.y + nz * a.z;
    const int64_t q[4] = { std::llround(nx * 256.0), std::llround(ny * 256.0), std::llround(nz * 256.0), std::llround(d) };
    key = XXH3_64bits_withSeed(q, sizeof q, mhash);
    return true;
}
// ---- edges held on flat pictures (2026-11-15, the user's playtest: "grid-like lines on the select-screen backgrounds") ---------------
// A picture too big for the texture memory is drawn as a grid of pieces, a tile each (the Superstar Select's backdrop: 64 x 30), most
// with the tile's repeat on. Drawn filtered at more than the game's 320 x 240, a piece's outer pixels sample half a texel past its
// tile's edge, and with the repeat on that is the tile's far side: every seam came out a line, half of the tile's other edge (QA
// 2026-11-15_095451 shot 011.7s: the seam pixels' change against their neighbours follows the far edge's, correlation 0.998). The N64
// at its own size never samples there. So a flat draw (2D: rectangles, or triangles through a matrix with no perspective or put on
// the screen by G_MODIFYVTX) whose texture coordinates all stay within its tile, on an axis, has that axis's edges held (clamped)
// instead: the same picture inside, no bleed at its edges. One that runs past its tile -- a pattern repeated across, a rectangle
// carried past the picture's sides for a wider screen (rect) -- keeps the repeat. 3D world draws keep theirs (a tiled floor's
// pieces, each 0..1 of a seamless picture, want it). The span is in the shader's own terms: s x uv.xy + uv.zw, 0..1 the tile.
struct UvSpan { float u0, u1, v0, v1, half_u, half_v; bool flat; };
static std::vector<UvSpan> spans_;     // (one for each draw of the frame being built, building_.draws, in step)
static void span_new(Frame& f, const UvSpan& sp) { spans_.resize(f.draws.size() - 1); spans_.push_back(sp); }
static void span_add(const Frame& f, const Draw& d, float s_, float t_) {
    const size_t i = size_t(&d - f.draws.data());
    if (i >= spans_.size()) return;
    UvSpan& sp = spans_[i];
    const float u = s_ * d.cb.uv[0] + d.cb.uv[2], v = t_ * d.cb.uv[1] + d.cb.uv[3];
    sp.u0 = std::min(sp.u0, u); sp.u1 = std::max(sp.u1, u); sp.v0 = std::min(sp.v0, v); sp.v1 = std::max(sp.v1, v);
}
static void span_3d(const Frame& f, const Draw& d) { const size_t i = size_t(&d - f.draws.data()); if (i < spans_.size()) spans_[i].flat = false; }
static void hold_edges(Frame& f) {
    for (size_t i = 0; i < f.draws.size() && i < spans_.size(); i++) {
        Draw& d = f.draws[i]; const UvSpan& sp = spans_[i];
        if (!sp.flat || !d.count || d.tex < 0 || sp.u0 > sp.u1) continue;     // (flat, drawn, a picture of the game's, its coordinates seen)
        if (sp.u0 >= -sp.half_u && sp.u1 <= 1.0f + sp.half_u) d.cms |= 2u;
        if (sp.v0 >= -sp.half_v && sp.v1 <= 1.0f + sp.half_v) d.cmt |= 2u;
    }
    spans_.clear();
}
