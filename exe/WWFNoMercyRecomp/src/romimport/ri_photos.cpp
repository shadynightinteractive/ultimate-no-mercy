// tv_carriers.h: no generator of it was left. Found again (2026-11-19, p3photos): the header's 72 file numbers, all in
// 0x4859-0x48C4 (108 files), were compared with No Mercy's files there (photos_lost.py, its "tv" part): No Mercy keeps two
// kinds of 64 x 64 TEX picture in that range -- CI4 ones (2096 bytes: 16 colours) and CI8 ones (4624 bytes: a 16-byte TEX
// header with 8 bits a pixel and 256 colours, the 512-byte palette, the 4096-byte picture) -- and the 72 are exactly the
// CI8 ones, in file order (the frames of its Titantron videos). Each one's 32 signature bytes are its palette's first 32
// (the file's bytes 16-48: the first 16 colours).
constexpr uint32_t TV_FIRST = 0x4859, TV_LAST = 0x48C4;   // (the header's own comment: "files 0x4859-0x48C4")
bool ci8_frame(const Bytes* b) {
    // "TEX\0", width 64, height 64 (u16 each), then 8 bits a pixel, and 256 colours (u16 at 10); 4624 bytes in all
    return b && b->size() == 16 + 512 + 4096 && !memcmp(b->data(), "TEX\0", 4) && be16(*b, 4) == 64 && be16(*b, 6) == 64 &&
           (*b)[8] == 8 && be16(*b, 10) == 0x100;
}
std::string tv_carriers_h(const RomFiles& nm) {
    std::vector<uint32_t> ids;
    for (uint32_t f = TV_FIRST; f <= TV_LAST; f++) if (ci8_frame(nm.get(f))) ids.push_back(f);
    if (ids.size() != 72) fail("tv_carriers: No Mercy has %zu Titantron frame files in 0x%X-0x%X, not 72", ids.size(), TV_FIRST, TV_LAST);
    std::string t =
        "// The game's own Titantron frame files the videos' frames are shown in the place of (72: a video's\n"
        "// length): files 0x4859-0x48C4, 64 x 64 CI8 TEX pictures of the game's videos. tv_carrier_sig: 32 bytes\n"
        "// of each one's palette, to see a read of one is done.\n"
        "#define TV_CARRIERS 72\n"
        "static const u16 tv_carrier[TV_CARRIERS] = {\n";
    for (size_t i = 0; i < ids.size(); i++) t += strf(i ? ",0x%04X" : "0x%04X", ids[i]);
    t += "\n};\nstatic const u8 tv_carrier_sig[TV_CARRIERS][32] = {\n";
    for (uint32_t f : ids) {
        const Bytes& b = nm(f);
        t += "{";
        for (int j = 16; j < 48; j++) t += strf(j > 16 ? ",0x%02X" : "0x%02X", b[j]);
        t += "},\n";
    }
    return t + "};\n";
}

