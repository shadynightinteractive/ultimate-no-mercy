// ---- the photos' C arrays ----------------------------------------------------------------------------------------------
// A select photo: 64 x 64 CI4 -- its palette (16 colours, 32 bytes) then its picture (2048 bytes). Written as mkportphotos.py
// c_arrays writes them (and as the developer's mideon / droz / bigshow headers have them): 16 bytes a line, each "0x%02X,".
void c_arrays(std::string& out, const std::string& prefix, const uint8_t* tlut, const uint8_t* ci4) {
    auto rows = [&](const uint8_t* p, size_t n) {
        for (size_t i = 0; i < n; i += 16) {
            out += "   ";
            for (size_t j = i; j < i + 16 && j < n; j++) out += strf(" 0x%02X,", p[j]);
            out += "\n";
        }
    };
    out += "static const u8 " + prefix + "_photo_tlut[32] = {\n";
    rows(tlut, 32);
    out += "};\nstatic const u8 " + prefix + "_photo_ci4[2048] = {\n";
    rows(ci4, 2048);
    out += "};\n";
}

// ---- No Mercy Plus V3's select photos ------------------------------------------------------------------------------------
// No Mercy Plus V3 keeps photo p (its Superstar Select's) as a TEX file of its own at 0x4C21 + p: a 16-byte TEX header, the
// 32-byte palette, the 2048-byte CI4 picture (2096 bytes; mod\gen\mkphotos.py). Which photo an ordinal shows: its costume
// struct (0x14 bytes a costume, four an ordinal, at 0x80401010 in its RAM at the Superstar Select: gen/mkroster.py
// NM_STRUCTS) names the appearance record (u16 at + 0xE) in its file 1 (0x26 bytes a record), whose byte 0x25 is the photo
// (gen/mkparts.py nm_app / APP_FIELDS "photo"). Costume 1 (index 0) is the one taken, as mkphotos.py takes it.
constexpr uint32_t NM_STRUCTS = 0x80401010;     // (gen/mkroster.py)
constexpr uint32_t NM_PHOTO_FILE0 = 0x4C21;     // (gen/mkphotos.py)
constexpr uint32_t APP_SIZE = 0x26, APP_PHOTO = 0x25;

struct NmPlus {
    const RomFiles* f = nullptr;
    Bytes ram;                                   // the nm_pick RAM image (make_data.py's, ri_images)
    // the photo TEX file of ordinal o's costume 1
    const Bytes& photo_file(int o) const {
        uint32_t app = be16(ram, (NM_STRUCTS + o * 0x50 + 0xE) & 0x7FFFFF);
        const Bytes& apps = (*f)(1);
        if ((app + 1) * APP_SIZE > apps.size()) fail("photos: No Mercy Plus V3's ordinal %d names no appearance record", o);
        uint32_t file = NM_PHOTO_FILE0 + apps[app * APP_SIZE + APP_PHOTO];
        const Bytes& b = (*f)(file);
        if (b.size() != 2096 || memcmp(b.data(), "TEX\0", 4))
            fail("photos: No Mercy Plus V3's file 0x%X (ordinal %d's photo) isn't a 64 x 64 CI4 picture", file, o);
        return b;
    }
};

// mod\gen\mkphotos.py -> photos_nm.h. Its list is gen/mkparts.py OVR2: the No Mercy Plus V3 Superstars added after the
// Meanie, (key, No Mercy Plus V3 ordinal), our photo numbers 105 on in that order -- our constant table (mkparts' own).
std::string photos_nm_h(const NmPlus& N) {
    static const std::pair<const char*, int> OVR2[] = { { "petegas", 80 }, { "rodney", 81 }, { "joeyabs", 82 },
        { "taker99", 83 }, { "raven", 84 }, { "regal", 86 }, { "tiger", 89 } };
    constexpr int PHOTO0 = 105;                  // (mkparts.py: OVR2's photos 105 on)
    const int n = (int)(sizeof OVR2 / sizeof OVR2[0]);
    std::string t = "// generated by gen/mkphotos.py: No Mercy Plus V3's photos for the Superstars after the Meanie\n"
                    "typedef struct { u8 photo; u8 tlut[32]; u8 ci4[2048]; } NmPhoto;\n" +
                    strf("#define NM_PHOTOS_N %d\n", n) + "static const NmPhoto nm_photos[NM_PHOTOS_N] = {\n";
    for (int i = 0; i < n; i++) {
        const Bytes& b = N.photo_file(OVR2[i].second);
        auto list = [&](size_t a, size_t e) {
            std::string s;
            for (size_t j = a; j < e; j++) s += strf(j == a ? "0x%02X" : ", 0x%02X", b[j]);
            return s;
        };
        t += strf("  { %d, { ", PHOTO0 + i) + list(16, 48) + " },  // " + OVR2[i].first + "\n    { " + list(48, b.size()) + " } },\n";
    }
    return t + "};\n";
}

