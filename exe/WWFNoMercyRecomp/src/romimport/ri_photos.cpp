// ---- tools\romrender\mkportphotos.py ------------------------------------------------------------------------------------
std::vector<std::pair<std::string, std::string>> port_photo_headers(Roms& R, const RiData& D) {
    std::vector<std::pair<std::string, std::string>> out;
    const RomFiles* nm = R.files("nomercy");
    // (the renderer reads No Mercy's files; c2hands: WM2000 optional -- port_photo_models; arenasplit 2026-11-24: Revenge too --
    //  WrestleMania 2000 alone gives Jarrett's and the Meanie's)
    if (!nm || (!R.files("revenge") && !R.files("wm2000"))) return out;
    std::string how = PHOTO_HOW;
    how = how.substr(how.find(": ") + 2);                      // (RM.PHOTO_HOW.split(": ", 1)[1])
    const std::string head =
        "// generated by tools/romrender/mkportphotos.py: the photo for the Superstar Select (64 x 64 CI4, 16 colours, 0 clear)\n"
        "// RENDERED by our renderer from his own model as gen/wmport.py builds it (costume 1): " + how + ".\n";
    std::string rev = head + "// The Revenge ports, gen/wmport.py REV_PORTED's order. { photo, palette, picture }\n";
    int n_rev = 0;
    std::vector<std::pair<std::string, std::string>> wm;
    for (auto& M : port_photo_models(R, D)) {
        Bytes photo = photo_from_pool(M.desc, M.files, *nm);   // (W.Files() data, then No Mercy's: rr_model.pack_getter)
        if (photo.size() != 2080) fail("portphotos: %s's photo is %zu bytes", M.name.c_str(), photo.size());
        if (M.name == "jarrett" || M.name == "meanie") {
            std::string t = head;
            c_arrays(t, M.name == "jarrett" ? "jj" : "bm", photo.data(), photo.data() + 32);
            wm.push_back({ M.name == "jarrett" ? "jarrett_photo.h" : "meanie_photo.h", t });
        } else {
            c_arrays(rev, M.name == "brethart" ? "bret" : M.name, photo.data(), photo.data() + 32);   // (ARRAY: Bret's)
            n_rev++;
        }
    }
    if (n_rev) out.push_back({ "rev_photos.h", rev });
    for (auto& h : wm) out.push_back(h);
    return out;
}

// ---- the lost producers ------------------------------------------------------------------------------------------------
std::vector<std::pair<std::string, std::string>> nm_photo_headers(Roms& R, const RiData& D) {
    std::vector<std::pair<std::string, std::string>> out;
    if (const RomFiles* f = R.files("nmplus_v3")) {
        NmPlus N;
        N.f = f;
        N.ram = make_image("nm_pick", D.dir / "loadmaps", R);
        out.push_back({ "photos_nm.h", photos_nm_h(N) });
        for (auto& P : ONE_PHOTOS) {
            const Bytes& b = N.photo_file(P.ordinal);
            std::string t = P.comment;
            c_arrays(t, P.prefix, b.data() + 16, b.data() + 48);
            out.push_back({ P.file, t });
        }
    }
    if (const RomFiles* nm = R.files("nomercy")) out.push_back({ "tv_carriers.h", tv_carriers_h(*nm) });
    return out;
}

