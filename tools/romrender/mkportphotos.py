"""mkportphotos.py (romrender, 2026-11-18): the built-in ported Superstars' select photos RENDERED by our renderer (the user's
decision A: no screenshot ships) -- the same portrait rule as every import's (rr_model.photo_from_model), from each man's own
model as gen/wmport.py builds it (costume 1):

  src/rev_photos.h     the 18 Revenge ports (gen/wmport.py REV_PORTED, in its order; arrays <name>_photo_tlut / _ci4)
  src/jarrett_photo.h  Jeff Jarrett (WrestleMania 2000's man 29: jj_photo_*)
  src/meanie_photo.h   The Blue Meanie (WrestleMania 2000's man 41: bm_photo_*)

Was: crops of Revenge's Costume Change screen (revport/mkphoto.py), a recoloured WM2000 Titantron frame (Jarrett), a crop of
WM2000's select screen (meanie/mkphoto.py). Run where gen/wmport.py runs (the ROM-only tree: its captures are the ROM-built
models).    python mkportphotos.py <out folder>     (the mod's src\\ to replace them; they change the mod build)"""
import os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(SRC, "mod", "gen")); sys.path.insert(0, HERE)
import wmport as W
import rr_model as RM

ARRAY = {"brethart": "bret"}           # (rev_photos.h's array names: the key, but Bret's)

def c_arrays(prefix, photo, about):
    out = ["static const u8 %s_photo_tlut[32] = {" % prefix]
    for i in range(0, 32, 16): out.append("    " + " ".join("0x%02X," % b for b in photo[i:i + 16]))
    out += ["};", "static const u8 %s_photo_ci4[2048] = {" % prefix]
    for i in range(32, 2080, 16): out.append("    " + " ".join("0x%02X," % b for b in photo[i:i + 16]))
    out += ["};"]
    return out

def wm_port_desc(k, c, F):
    """a WrestleMania 2000 port's descriptor, costume c, its files into F (gen/wmport.py build_all's PORTED loop), marked
    as WM2000's model (skel.h SKEL_MAGIC: joined and drawn WM2000's way, its neck too)"""
    ram = W.ensure_capture(k, c)
    wd, parts = W.capture(ram, 0)
    nm = bytearray(W.nm_descriptor(wd))
    for o in list(range(8, 0xB0, 8)) + list(range(0xC8, 0xE0, 8)): nm[o:o + 6] = bytes(6)
    for p in parts:
        o = p["at"] if p["k"] <= 20 else 0xC8 + 8 * (p["k"] - 22)
        t, q = F.pair(p["tex"], p["pal"]) if p["tex"] else (0, 0)
        struct.pack_into(">HHH", nm, o, F.one(W.wfile(p["mesh"])), t, q)
    struct.pack_into(">I", nm, W.SKEL_MAGIC_AT, W.SKEL_MAGIC_WM)
    return bytes(nm)

def photo_of(desc, F):
    return RM.photo_from_model(desc, RM.pack_getter(desc, F.data, W.WMP_FILE0, W.nm_files_reader()))

def main():
    out = sys.argv[1]; os.makedirs(out, exist_ok=True)
    head = ["// generated by tools/romrender/mkportphotos.py: the photo for the Superstar Select (64 x 64 CI4, 16 colours, 0 clear)",
            "// RENDERED by our renderer from his own model as gen/wmport.py builds it (costume 1): %s." % RM.PHOTO_HOW.split(": ", 1)[1]]
    wm_ref = {p["k"]: (p["tex"], p["pal"]) for p in W.capture(W.ensure_capture(W.PORTED[0][1], 0), 0)[1]}
    L = list(head) + ["// The Revenge ports, gen/wmport.py REV_PORTED's order. { photo, palette, picture }"]
    for name in [n for n in W.REV_PORTED if n not in W.revbanks.BY]:     # (not the second looks gen/revbanks.py adds)
        F = W.Files(); desc = W.rev_port_desc(name, 0, F, wm_ref)
        L += c_arrays(ARRAY.get(name, name), photo_of(desc, F), name)
    open(os.path.join(out, "rev_photos.h"), "w", newline="\n").write("\n".join(L) + "\n")
    for name, k in W.PORTED:
        F = W.Files(); desc = wm_port_desc(k, 0, F)
        fn, prefix = {"jarrett": ("jarrett_photo.h", "jj"), "meanie": ("meanie_photo.h", "bm")}[name]
        open(os.path.join(out, fn), "w", newline="\n").write("\n".join(head + c_arrays(prefix, photo_of(desc, F), name)) + "\n")
    print("rev_photos.h (%d), jarrett_photo.h, meanie_photo.h -> %s" % (len([n for n in W.REV_PORTED if n not in W.revbanks.BY]), out))
    return 0

if __name__ == "__main__":
    sys.exit(main())
