"""photos_lost.py (phase3 p3photos, 2026-11-19): the developer's proof of the "lost producers" rules -- the mod headers no
chain step makes, whose generators were never kept (or never run ROM-only), made again by exe src\\romimport\\ri_photos.cpp:

  photos_nm.h      mod\\gen\\mkphotos.py: No Mercy Plus V3's photo TEX files (0x4C21 + photo) for gen/mkparts.py OVR2's men
  mideon_photo.h   }  No Mercy Plus V3's Superstar Select photos: the same rule as mkphotos.py's, for its ordinals
  droz_photo.h     }  79 (Mideon), 75 (Droz) and 5 (Big Show)
  bigshow_photo.h  }
  tv_carriers.h    No Mercy's Titantron frame files: the CI8 64 x 64 TEX pictures among files 0x4859-0x48C4, in file order,
                   and the first 32 bytes of each one's palette

Reads the ROMs only (tools\\romimport\\roms.py: roms\\ by fingerprint; the No Mercy Plus V3 RAM image from its load map,
images.py build) and the developer's headers to compare with (<private>\\generated\\mod\\src). Writes nothing.

    python photos_lost.py --private <private>             each header made by its rule: SAME / DIFFERENT vs the reference
    python photos_lost.py --private <private> --search    the search that found the rules: where each reference photo's bytes
                                                          sit in No Mercy Plus V3's and No Mercy's files; what files
                                                          0x4859-0x48C4 are"""
import argparse, json, os, re, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.dirname(HERE))
from roms import Roms
import images

NM_STRUCTS, NM_PHOTO_FILE0 = 0x80401010, 0x4C21     # (gen/mkroster.py, gen/mkphotos.py)
OVR2 = [("petegas", 80), ("rodney", 81), ("joeyabs", 82), ("taker99", 83), ("raven", 84), ("regal", 86), ("tiger", 89)]
ONE = [("mideon_photo.h", "md", 79,
        "// Mideon's photo for the Superstar Select (64 x 64 CI4, the photos' format): No Mercy Plus V3's, taken from\n"
        "// its Superstar Select.\n"),
       ("droz_photo.h", "dz", 75,
        "// Droz's photo for the Superstar Select (64 x 64 CI4, the photos' format): No Mercy Plus V3's, taken from\n"
        "// its Superstar Select.\n"),
       ("bigshow_photo.h", "bs", 5,
        "// Big Show's photo for the Superstar Select (a 64 x 64 CI4 picture, the photos' format): the\n"
        "// digitized photo No Mercy Plus V3 gives him (taken from its Superstar Select).\n")]
TV_FIRST, TV_LAST = 0x4859, 0x48C4

def photo_file(F, ram, o):
    """No Mercy Plus V3's ordinal o's photo TEX file (costume 1): its costume struct -> appearance record -> byte 0x25"""
    app = struct.unpack_from(">H", ram, (NM_STRUCTS + o * 0x50 + 0xE) & 0x7FFFFF)[0]
    f = NM_PHOTO_FILE0 + F(1)[app * 0x26 + 0x25]
    b = F(f)
    assert len(b) == 2096 and b[:4] == b"TEX\0", (o, hex(f))
    return f, b

def c_arrays(prefix, tlut, ci4):
    out = ["static const u8 %s_photo_tlut[32] = {" % prefix]
    for i in range(0, 32, 16): out.append("    " + " ".join("0x%02X," % b for b in tlut[i:i + 16]))
    out += ["};", "static const u8 %s_photo_ci4[2048] = {" % prefix]
    for i in range(0, 2048, 16): out.append("    " + " ".join("0x%02X," % b for b in ci4[i:i + 16]))
    return "\n".join(out + ["};"]) + "\n"

def ci8_frame(b):
    return (b is not None and len(b) == 4624 and b[:4] == b"TEX\0" and struct.unpack_from(">HH", b, 4) == (64, 64)
            and b[8] == 8 and struct.unpack_from(">H", b, 10)[0] == 0x100)

def make(R):
    out = {}
    F = R.files("nmplus_v3")
    if F is not None:
        ram = images.build(json.load(open(os.path.join(os.path.dirname(HERE), "loadmaps", "nm_pick.json"))), R)
        L = ["// generated by gen/mkphotos.py: No Mercy Plus V3's photos for the Superstars after the Meanie",
             "typedef struct { u8 photo; u8 tlut[32]; u8 ci4[2048]; } NmPhoto;",
             "#define NM_PHOTOS_N %d" % len(OVR2), "static const NmPhoto nm_photos[NM_PHOTOS_N] = {"]
        for i, (k, o) in enumerate(OVR2):
            b = photo_file(F, ram, o)[1]
            L.append("  { %d, { %s },  // %s\n    { %s } }," % (105 + i, ", ".join("0x%02X" % x for x in b[16:48]), k,
                     ", ".join("0x%02X" % x for x in b[48:])))
        out["photos_nm.h"] = "\n".join(L + ["};"]) + "\n"
        for fn, prefix, o, comment in ONE:
            b = photo_file(F, ram, o)[1]
            out[fn] = comment + c_arrays(prefix, b[16:48], b[48:])
    N = R.files("nomercy")
    if N is not None:
        ids = [f for f in range(TV_FIRST, TV_LAST + 1) if ci8_frame(N(f))]
        assert len(ids) == 72, len(ids)
        t = ("// The game's own Titantron frame files the videos' frames are shown in the place of (72: a video's\n"
             "// length): files 0x4859-0x48C4, 64 x 64 CI8 TEX pictures of the game's videos. tv_carrier_sig: 32 bytes\n"
             "// of each one's palette, to see a read of one is done.\n"
             "#define TV_CARRIERS 72\nstatic const u16 tv_carrier[TV_CARRIERS] = {\n")
        t += ",".join("0x%04X" % f for f in ids) + "\n};\nstatic const u8 tv_carrier_sig[TV_CARRIERS][32] = {\n"
        t += "".join("{%s},\n" % ",".join("0x%02X" % x for x in N(f)[16:48]) for f in ids)
        out["tv_carriers.h"] = t + "};\n"
    return out

def ref_arrays(text):
    return [bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})\b", m.group(1)))
            for m in re.finditer(r"\[\d+\]\s*=\s*\{(.*?)\};", text, re.S)]

def unpacked_size(F, i):
    """file i's unpacked size from the table and its first u32 alone (no unpacking): the search's filter"""
    a = (F.t[i - 1] & ~1) + F.base; b = (F.t[i] & ~1) + F.base
    if b < a or b > len(F.rom): return None
    if F.t[i - 1] & 1 and b - a >= 4: return struct.unpack_from(">I", F.rom, a)[0]
    return b - a

def search(R, gen):
    """where each reference photo's palette + picture sit whole (a 2096-byte TEX file: header, 32, 2048), and the frames"""
    want = {fn: ref_arrays(open(os.path.join(gen, fn), encoding="ascii").read()) for fn, _, _, _ in ONE}
    for game in ("nmplus_v3", "nomercy"):
        F = R.files(game)
        if F is None: print("(no %s)" % game); continue
        n = 0
        for i in range(1, F.n):
            if unpacked_size(F, i) != 2096: continue
            b = F(i); n += 1
            for fn, (tl, ci) in want.items():
                if b[16:48] == tl and b[48:] == ci: print("  %-16s whole in %s file 0x%04X" % (fn, game, i))
        print("%s: %d files of 2096 bytes searched" % (game, n))
    F = R.files("nmplus_v3")
    ram = images.build(json.load(open(os.path.join(os.path.dirname(HERE), "loadmaps", "nm_pick.json"))), R)
    for o in range(1, 0x60):                       # which ordinal shows which photo (costume 1)
        try: f, _ = photo_file(F, ram, o)
        except (AssertionError, IndexError, TypeError): continue
        if f in (0x4C6B, 0x4C85, 0x4C8E): print("  No Mercy Plus V3 ordinal %d (ID 0x%04X): photo file 0x%04X" %
                                                 (o, struct.unpack_from(">H", ram, (NM_STRUCTS + o * 0x50) & 0x7FFFFF)[0], f))
    N = R.files("nomercy")
    ref = open(os.path.join(gen, "tv_carriers.h"), encoding="ascii").read()
    listed = [int(x, 16) for x in re.search(r"tv_carrier\[TV_CARRIERS\] = \{\s*(.*?)\s*\};", ref, re.S).group(1).split(",")]
    for f in range(TV_FIRST, TV_LAST + 1):
        b = N(f)
        print("  0x%04X %5s bytes %-6s %s" % (f, len(b) if b else "-", "CI8" if ci8_frame(b) else "CI4" if b and b[8] == 4 else "?",
                                              "listed" if f in listed else ""))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--private", required=True); ap.add_argument("--search", action="store_true")
    a = ap.parse_args()
    R = Roms(os.path.join(a.private, "roms"))
    gen = os.path.join(a.private, "generated", "mod", "src")
    if a.search: search(R, gen); return 0
    bad = 0
    for fn, text in make(R).items():
        ref = open(os.path.join(gen, fn), "rb").read()
        same = text.encode("ascii") == ref
        bad += not same
        print("%-16s %s" % (fn, "SAME" if same else "DIFFERENT"))
    return 1 if bad else 0

if __name__ == "__main__":
    sys.exit(main())
