#!/usr/bin/env python3
"""replay (2026-11-14): the structures nm_replay hashes each retrace, from memory_groundwork's map.json.

  python gen_replay_map.py <map.json> <out nm_replay_map.h>

Every structure of the map with its fixed members (address, end), in the map's own order, members sorted by address.
Which of them a run hashes is the run's choice (NM_REPLAY_STRUCTS, nm_replay.cpp): the engine group unless it says.
A member is hashed as the N64's bytes of [address, end) (big-endian, as the game sees them), so that a build which keeps
a structure another way can hash its encoder's output and get the same number (DESIGN.md P3).

The header carries the map's version and a digest of the table, written into every hash log, so two logs made from
different tables are never compared as if they were the same.
"""
import hashlib, json, sys


def main(map_path, out_path):
    m = json.load(open(map_path, encoding="utf-8"))
    rows = []      # (structure id, group, member name, address, end, kind, element size)
    for s in m["structures"]:
        members = []
        for mem in s.get("members") or []:
            try:
                a, e = int(mem["address"], 16), int(mem["end"], 16)
            except (KeyError, TypeError, ValueError):
                continue
            if e <= a:
                continue
            members.append((a, e, mem.get("name") or mem.get("id"), mem.get("kind") or "", int(mem.get("element_size") or 0)))
        for a, e, name, kind, size in sorted(members):
            rows.append((s["id"], s.get("group") or "", name, a, e, kind, size))
    digest = hashlib.sha256("\n".join("%s %s %08X %08X" % (r[0], r[2], r[3], r[4]) for r in rows).encode()).hexdigest()[:16]

    def cstr(t):
        return '"' + str(t).replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = []
    out.append("// GENERATED by scratch/agents/replay/tools/gen_replay_map.py from memory_groundwork's map.json (map %s): do not edit." % m.get("version"))
    out.append("// The structures nm_replay.cpp hashes each retrace: each fixed member's address and end, in N64 addresses.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("namespace nm_replay_map {")
    out.append("struct Member { const char* structure; const char* group; const char* name; uint32_t address, end; const char* kind; uint32_t element_size; };")
    out.append("constexpr const char* MAP_VERSION = %s;" % cstr(m.get("version")))
    out.append("constexpr const char* TABLE_DIGEST = %s;" % cstr(digest))
    out.append("constexpr Member MEMBERS[] = {")
    for r in rows:
        out.append("    { %s, %s, %s, 0x%08Xu, 0x%08Xu, %s, %du }," % (cstr(r[0]), cstr(r[1]), cstr(r[2]), r[3], r[4], cstr(r[5]), r[6]))
    out.append("};")
    out.append("constexpr int MEMBER_COUNT = %d;" % len(rows))
    out.append("}  // namespace nm_replay_map")
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%d members of %d structures, digest %s -> %s" % (len(rows), len({r[0] for r in rows}), digest, out_path))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
